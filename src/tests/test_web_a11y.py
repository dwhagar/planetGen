from tests.bughunt_support import mysql_argv, run_cli  # noqa: E402
from tests.conftest import _test_server_kwargs  # noqa: E402

AXE_JS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vendor", "axe-core", "axe.min.js")

VIEWPORTS = {"phone": {"width": 390, "height": 844}, "desktop": {"width": 1280, "height": 800}}
SCHEMES = ("light", "dark")

SCREENSHOT_DIR = os.environ.get("PLANETGEN_A11Y_SCREENSHOTS")
"""str: When set, a full-page screenshot of every page checked is saved
there as `<endpoint>-<phone|desktop>-<light|dark>.png` (CI uploads them
as an artifact)."""

AXE_TAGS = ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]
BLOCKING_IMPACTS = {"serious", "critical"}

# Recorded before any page script runs; CDP-injected, so the page's CSP
# does not block it.
CSP_LISTENER = """
window.__cspViolations = [];
document.addEventListener("securitypolicyviolation", function (e) {
  window.__cspViolations.push(e.violatedDirective + " blocked " + (e.blockedURI || "inline") +
                              " at " + (e.sourceFile || "") + ":" + (e.lineNumber || 0));
});
"""


class _EndpointCatalog:
    """The GET endpoints of the `web` blueprint, read once at collection
    time from an app built with the default config (building the app
    touches no database)."""

    @staticmethod
    def endpoints():
        app = create_app(Config)
        found = {}
        for rule in app.url_map.iter_rules():
            if rule.endpoint.startswith("web.") and "GET" in rule.methods:
                found.setdefault(rule.endpoint, rule)
        return sorted(found)


PAGE_ENDPOINTS = _EndpointCatalog.endpoints()


