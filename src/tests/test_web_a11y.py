def _page_url(app, endpoint, samples):
    rule = next(r for r in app.url_map.iter_rules() if r.endpoint == endpoint)
    missing = sorted(arg for arg in rule.arguments if arg not in samples)
    if missing:
        pytest.fail(f"{endpoint} ({rule.rule}) takes {', '.join(missing)}: add a sample value "
                    f"to sample_params in {os.path.basename(__file__)}")
    with app.test_request_context("/"):
        from flask import url_for
        return url_for(endpoint, **{arg: samples[arg] for arg in rule.arguments})


