def _axe_blocking(page, axe_source, context=None):
    if not page.evaluate("typeof window.axe !== 'undefined'"):
        page.evaluate(axe_source)
    result = page.evaluate(
        """([context, tags]) => axe.run(context ? document.querySelector(context) : document,
                                        {runOnly: {type: "tag", values: tags}, resultTypes: ["violations"]})""",
        [context, AXE_TAGS],
    )
    problems = []
    for violation in result["violations"]:
        if violation["impact"] not in BLOCKING_IMPACTS:
            continue
        nodes = []
        for node in violation["nodes"][:5]:
            checks = node.get("any") or node.get("all") or node.get("none") or [{}]
            nodes.append(f"{' '.join(map(str, node['target']))}: {checks[0].get('message', '')}")
        problems.append(f"axe {violation['id']} ({violation['impact']}): {violation['help']}\n      "
                        + "\n      ".join(nodes))
    return problems


HEADING_AUDIT_JS = """() => {
    const shown = el => el.checkVisibility ? el.checkVisibility() : el.getClientRects().length > 0;
    const label = el => el.tagName.toLowerCase() + (el.id ? "#" + el.id : "") +
                        (el.className && typeof el.className === "string" ? "." + el.className.trim().split(/\\s+/).join(".") : "");
    const heads = [...document.querySelectorAll("h1,h2,h3,h4,h5,h6")].filter(h => shown(h) && !h.closest("sl-dialog, dialog, [hidden]"));
    const out = [];
    const h1s = heads.filter(h => h.tagName === "H1");
    if (h1s.length !== 1) out.push("expected one h1, found " + h1s.length);
    let previous = 0;
    for (const h of heads) {
        const level = Number(h.tagName[1]);
        if (previous === 0 && level !== 1) out.push("the first heading is " + label(h) + ", not an h1");
        else if (level > previous + 1) out.push(label(h) + " (h" + level + ") skips a level after h" + previous);
        previous = level;
    }
    for (const table of document.querySelectorAll("table")) {
        if (!shown(table) || table.closest("sl-dialog, dialog, [hidden]")) continue;
        if (table.querySelector(":scope > caption") || table.getAttribute("aria-label") || table.getAttribute("aria-labelledby")) continue;
        const holder = table.closest("section, details, article, form, aside");
        const before = h => table.compareDocumentPosition(h) & Node.DOCUMENT_POSITION_PRECEDING;
        const owner = holder && heads.some(h => holder.contains(h) && before(h));
        if (!owner) out.push(label(table) + " has no heading, caption or label");
    }
    return out;
}"""


def _heading_outline(page):
    """UX.195: one h1, no skipped level in document order, and every visible table under a heading of its section or
    carrying a caption or label."""
    return [f"heading outline: {problem}" for problem in page.evaluate(HEADING_AUDIT_JS)]


def _overflow(page):
    widths = page.evaluate(
        "({doc: document.documentElement.scrollWidth, body: document.body.scrollWidth,"
        " view: document.documentElement.clientWidth})"
    )
    if max(widths["doc"], widths["body"]) > widths["view"]:
        wide = page.evaluate(
            """() => {
                const view = document.documentElement.clientWidth, out = [];
                for (const el of document.querySelectorAll("body *")) {
                    const r = el.getBoundingClientRect();
                    let clipped = false;
                    for (let up = el.parentElement; up && up !== document.body; up = up.parentElement) {
                        if (getComputedStyle(up).overflowX !== "visible") { clipped = true; break; }
                    }
                    if (!clipped && r.right > view + 1 && getComputedStyle(el).position !== "fixed") {
                        out.push(el.tagName.toLowerCase() + (el.id ? "#" + el.id : "") +
                                 (el.className && typeof el.className === "string" ? "." + el.className.trim().split(/\\s+/).join(".") : "") +
                                 " right=" + Math.round(r.right));
                        if (out.length >= 5) break;
                    }
                }
                return out;
            }"""
        )
        return [f"horizontal overflow: scrollWidth {max(widths['doc'], widths['body'])} > "
                f"viewport {widths['view']} ({wide})"]
    return []


def _wait_for_components(page):
    """Waits until every Shoelace element on the page is defined and has rendered once.

    An `sl-option` is given its `option` role at once, but the `listbox` it needs as a parent is rendered inside its
    `sl-select`'s shadow root; axe run before that reported "aria-required-parent" (/admin/generate/system at phone/light
    in the TEST.385 run, though not at the other three viewport and scheme cases)."""
    page.evaluate("""async () => {
        const tags = new Set([...document.querySelectorAll("*")].map(e => e.localName).filter(n => n.startsWith("sl-")));
        await Promise.all([...tags].map(tag => customElements.whenDefined(tag)));
        await Promise.all([...document.querySelectorAll("*")].filter(e => e.localName.startsWith("sl-") && e.updateComplete)
                          .map(e => e.updateComplete));
    }""")


@pytest.mark.parametrize("scheme", SCHEMES)
@pytest.mark.parametrize("viewport", sorted(VIEWPORTS))
@pytest.mark.parametrize("endpoint", PAGE_ENDPOINTS)
def test_page_is_accessible_and_fits(browser, axe_source, base_url, page_targets, admin_token,
                                     endpoint, viewport, scheme):
    path, needs_admin = page_targets[endpoint]
    if path is None:
        pytest.skip(needs_admin)

    context = browser.new_context(viewport=VIEWPORTS[viewport], color_scheme=scheme,
                                  device_scale_factor=1, reduced_motion="reduce")
    if needs_admin:
        context.add_cookies([{"name": SESSION_COOKIE_NAME, "value": admin_token, "url": base_url}])
    context.add_init_script(CSP_LISTENER)
    page = context.new_page()
    problems = []
    page.on("console", lambda msg: msg.type == "error" and problems.append(f"console error: {msg.text}"))
    page.on("pageerror", lambda exc: problems.append(f"uncaught exception: {exc}"))
    # A request the page cancels itself (the map drops its tile fetch when the view moves on) ends ERR_ABORTED: on a
    # loaded machine the fetch is still under way when that happens (TEST.174, TEST.197). It is not a failed request.
    page.on("requestfailed", lambda req: "ERR_ABORTED" in str(req.failure)
            or problems.append(f"request failed: {req.url} ({req.failure})"))
    page.on("response", lambda resp: resp.status >= 400 and problems.append(
        f"HTTP {resp.status}: {resp.url}"))
    try:
        response = page.goto(base_url + path, wait_until="load")
        assert response.status == 200, f"{path} answered {response.status}"
        page.wait_for_timeout(100)
        _wait_for_components(page)

        if SCREENSHOT_DIR:
            os.makedirs(SCREENSHOT_DIR, exist_ok=True)
            page.screenshot(path=os.path.join(SCREENSHOT_DIR, f"{endpoint[4:]}-{viewport}-{scheme}.png"),
                            full_page=True)

        problems += _overflow(page)
        problems += _axe_blocking(page, axe_source)
        problems += _heading_outline(page)

        # Skip link: the first Tab stop, visible once focused, pointing at <main id="main">.
        page.keyboard.press("Tab")
        skip = page.evaluate(
            """() => {
                const a = document.activeElement, main = document.getElementById("main");
                const r = a.getBoundingClientRect();
                return {cls: a.className, href: a.getAttribute("href"),
                        main: !!main && main.tagName === "MAIN",
                        visible: r.width > 0 && r.height > 0 && r.top >= 0 && r.left >= 0 &&
                                 r.right <= document.documentElement.clientWidth};
            }"""
        )
        if not (skip["cls"] == "skip-link" and skip["href"] == "#main" and skip["main"] and skip["visible"]):
            problems.append(f"skip link is not the first, visible Tab stop into <main id=main>: {skip}")

        if page.locator('[aria-current="page"]').count() == 0:
            problems.append('no aria-current="page" anywhere on the page')

        # The skip link, focused above, sits over the header's left side.
        page.evaluate("document.activeElement && document.activeElement.blur()")
        header_menus = ["sl-dropdown.site-gear"]
        if page.locator("sl-dropdown.site-menu > [slot=trigger]").is_visible():
            header_menus.insert(0, "sl-dropdown.site-menu")
        if viewport == "phone":
            for menu in header_menus:
                page.locator(f"{menu} > [slot=trigger]").click()
                page.wait_for_timeout(50)
                problems += [f"({menu} open) {p}" for p in _overflow(page)]
                problems += [f"({menu} open) {p}" for p in _axe_blocking(page, axe_source, "header")]
                if SCREENSHOT_DIR and endpoint == "web.index":
                    page.screenshot(path=os.path.join(
                        SCREENSHOT_DIR, f"index-{menu.split('.')[1]}-{viewport}-{scheme}.png"))

        problems += [f"CSP violation: {v}" for v in page.evaluate("window.__cspViolations || []")]
    finally:
        context.close()

    assert not problems, f"{path} at {viewport}/{scheme}:\n  " + "\n  ".join(problems)


@pytest.mark.parametrize("scheme", SCHEMES)
def test_error_page_is_accessible(browser, axe_source, base_url, scheme):
    """The HTML 404 page (every missing page and bad id lands on it)."""
    for viewport in VIEWPORTS.values():
        context = browser.new_context(viewport=viewport, color_scheme=scheme, device_scale_factor=1)
        context.add_init_script(CSP_LISTENER)
        page = context.new_page()
        try:
            response = page.goto(base_url + "/no/such/page", wait_until="load")
            assert response.status == 404
            problems = _overflow(page) + _axe_blocking(page, axe_source)
            problems += [f"CSP violation: {v}" for v in page.evaluate("window.__cspViolations || []")]
            assert page.locator('a.skip-link[href="#main"]').count() == 1
        finally:
            context.close()
        assert not problems, f"404 page at {viewport['width']}px/{scheme}:\n  " + "\n  ".join(problems)
