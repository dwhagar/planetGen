# tests/test_web_a11y.py

"""
Phone-layout and accessibility checks for every Flask-served page, in a
real browser.

Every GET route of the `web` blueprint (read from the app's `url_map`, so
a page moved to Flask later is covered without touching this file) is
loaded in headless Chromium at 390px (a phone) and 1280px (a laptop), in
the light and the dark color scheme, and must have:

- no axe-core violations of serious or critical impact among the WCAG
  2.0/2.1 A and AA rules;
- no horizontal overflow (the document is never wider than the
  viewport);
- no console errors, uncaught exceptions, failed requests or
  Content-Security-Policy violations;
- a working skip link (the first Tab stop, visible when focused, pointing
  at `<main id="main">`) and an `aria-current="page"` marker.

At 390px the header's Menu is also opened and checked the same way.

The pages run against a small real database generated by `generate.py`
(a few sectors, a standalone system and some phenomena) through the
in-process API transport. A route's URL parameters take sample values
from that database (`SAMPLE_PARAMS` below); a new page with a parameter
name not listed there fails with a message saying to add it. A page that
answers anonymous visitors with a redirect is retried as a logged-in
admin; one that still redirects (a forwarder such as `/search` while the
search page is on CGI) is skipped.

Needs Playwright for Python with Chromium (`pip install playwright` and
`python -m playwright install chromium`, or `PLAYWRIGHT_BROWSERS_PATH`
pointing at an existing install) and the MySQL test server every other
database test uses. Without either, every test here is skipped. Set
`PLANETGEN_A11Y_SCREENSHOTS=<dir>` to also save a screenshot of each page. axe-core
is vendored under `tests/vendor/axe-core/` (MPL-2.0; see its LICENSE)
and injected through the DevTools protocol, so nothing is fetched at
test time and the page's own CSP stays in force.
"""

import os
import random
import threading
import uuid

import pymysql
import pytest

sync_api = pytest.importorskip("playwright.sync_api")

from werkzeug.serving import make_server  # noqa: E402

