@pytest.mark.parametrize("cls", [BlackHole, NeutronStar])
def test_load_star_system_reconstructs_anchored_compact_remnant(cls, mysql_config):
    # Regression test: load_star_system's single-star branch used to
    # unconditionally call Star.from_dict, silently reconstructing an
    # anchored compact remnant as a plain Star (losing its extra fields
    # and remnant-specific rendering) rather than dispatching on the
    # black_holes/neutron_stars satellite row. See _db._load_single_star.
    cfg = make_config()
    remnant = cls(cfg)
    system = StarSystem(system_config=cfg, compact_remnant=remnant)

    conn = _db.get_connection(mysql_config)
    try:
        with conn:
            system_id = _db.insert_star_system(conn, system, cfg)
        reloaded = _db.load_star_system(conn, system_id)
    finally:
        conn.close()

    assert isinstance(reloaded.star, cls)
    assert reloaded.star.name == remnant.name
    assert reloaded.star.type == remnant.type
    assert reloaded.star.yerkes_class == remnant.yerkes_class
    assert reloaded.star.mass_solar == pytest.approx(remnant.mass_solar)
    # Not exact string equality -- a DOUBLE round-trip through MySQL can
    # shift a formatted value's last displayed digit (e.g. temperature
    # rounding right at a .5 boundary), which is expected float noise, not
    # a reconstruction bug. The "Black Hole Data"/"Neutron Star Data"
    # header proves the remnant-specific to_paragraph_list() ran at all
    # (a plain Star would render "Star Data" instead).
    label = "Black Hole Data" if cls is BlackHole else "Neutron Star Data"
    assert label in str(reloaded.star)


