"""
Exotic stellar phenomena regression tests
==========================================

Covers the seven phenomena generated by `phenomenonGen.py`'s separate,
rarer generation mode -- `compactRemnant.BlackHole`/`NeutronStar`,
`nebulaData.Nebula`, `supernovaRemnantData.SupernovaRemnant`,
`roguePlanetData.RoguePlanet`/`InterstellarComet`,
`asteroidFieldData.AsteroidField` -- plus the
`StarSystem(compact_remnant=...)` integration point the two compact
remnants anchor through, and the galactic-orbital-motion fields every
standalone phenomenon shares (see `nebulaData.Nebula`'s docstring).

Generation-sanity/serialization/rendering tests need no database and always
run. The persistence tests at the bottom take the `mysql_config` fixture
(see `conftest.py`) and are skipped, not failed, when no MySQL test server
is configured/reachable.

Run with: pytest src/tests/test_phenomena.py
"""

import math

import pytest

from stellarObjects import _db, physical_constants, program_constants
from stellarObjects.asteroidFieldData import AsteroidField
from stellarObjects.compactRemnant import BlackHole, CompactRemnant, NeutronStar
from stellarObjects.config import SystemConfig
from stellarObjects.nebulaData import Nebula
from stellarObjects.roguePlanetData import InterstellarComet, RoguePlanet
from stellarObjects.supernovaRemnantData import SupernovaRemnant
from stellarObjects.systemData import StarSystem

TRIALS = 8

STANDALONE_PHENOMENON_CLASSES = [Nebula, SupernovaRemnant, RoguePlanet, InterstellarComet, AsteroidField]
"""list: Every phenomenon that is always standalone (never anchors a
StarSystem) -- shares the "== Name (Type) ==" header convention and the
galactic-orbital-motion fields, unlike BlackHole/NeutronStar (Star
subclasses, see test_compact_remnant_paragraph_list_renders_data_block_with_no_section_header)."""


def make_config(**overrides):
    cfg = SystemConfig()
    for attr, value in overrides.items():
        setattr(cfg, attr, value)
    return cfg


