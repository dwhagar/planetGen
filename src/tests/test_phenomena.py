    assert row["name"] == bh.name
    assert row["mass_solar"] == pytest.approx(bh.mass_solar)
    assert row["event_horizon_radius_km"] == pytest.approx(bh.event_horizon_radius_km)
    assert bool(row["has_accretion_disk"]) == bh.has_accretion_disk


