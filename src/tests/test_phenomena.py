def test_black_hole_mass_and_spin_within_configured_ranges():
    for _ in range(TRIALS):
        bh = BlackHole(make_config())
        assert (
            tuning.BLACK_HOLE_MASS_RANGE_SOLAR[0] <= bh.mass_solar <= tuning.BLACK_HOLE_MASS_RANGE_SOLAR[1]
            or tuning.BLACK_HOLE_INTERMEDIATE_MASS_RANGE_SOLAR[0] <= bh.mass_solar <= tuning.BLACK_HOLE_INTERMEDIATE_MASS_RANGE_SOLAR[1]
        )
        assert tuning.BLACK_HOLE_SPIN_RANGE[0] <= bh.spin <= tuning.BLACK_HOLE_SPIN_RANGE[1]
        assert bh.event_horizon_radius_km > 0
        assert bh.radius == bh.event_horizon_radius_km
        assert bh.yerkes_class == "BH"
        assert bh.lifespan == float('inf')
        if not bh.has_accretion_disk:
            # Only Hawking radiation (GEN.82): real, tiny, never zero.
            assert bh.luminosity == pytest.approx(hawking_luminosity_w(bh.mass_solar))
            assert bh.temperature == pytest.approx(hawking_temperature_k(bh.mass_solar))
            assert 0.0 < bh.habitable_zone[1] < 1e-20


def test_hawking_values_of_a_ten_solar_mass_black_hole():
    # T = hbar c^3 / (8 pi G M k_B) and L = hbar c^6 / (15360 pi G^2 M^2):
    # 6.17e-8 K and 9.00e-29 W at one solar mass (GEN.82).
    assert hawking_temperature_k(10.0) == pytest.approx(6.17e-9, rel=1e-2)
    assert hawking_luminosity_w(10.0) == pytest.approx(9.00e-31, rel=1e-2)


def test_black_hole_mass_class_matches_its_mass(monkeypatch):
    monkeypatch.setattr(tuning, "BLACK_HOLE_INTERMEDIATE_MASS_CHANCE", 1.0)
    bh = BlackHole(make_config())
    low, high = tuning.BLACK_HOLE_INTERMEDIATE_MASS_RANGE_SOLAR
    assert bh.mass_class == "intermediate" and low <= bh.mass_solar <= high
    assert bh.type == "Intermediate-Mass Black Hole"

    monkeypatch.setattr(tuning, "BLACK_HOLE_INTERMEDIATE_MASS_CHANCE", 0.0)
    bh = BlackHole(make_config())
    assert bh.mass_class == "stellar" and bh.type == "Stellar-Mass Black Hole"


def test_a_galaxy_holds_hundreds_of_intermediate_mass_black_holes():
    """GEN.259 (Boss, decision card, 2026-10-16): the Galaxy's 1e8 black holes (the central observed value of GEN.100)
    give hundreds of intermediate-mass ones, as the handful of candidates suggest, not the 1e5 of a 0.1% share."""
    black_holes = 1.0e8
    assert 100.0 <= black_holes * tuning.BLACK_HOLE_INTERMEDIATE_MASS_CHANCE <= 1000.0


def test_supermassive_black_hole_sits_still_and_glows_faintly():
    bh = BlackHole(make_config(), mass_class="supermassive")
    # A galaxy's own nucleus is "supermassive" whatever the draw gives (GEN.402: 38 percent are under the class minimum
    # of a tuning constant, two in a thousand under a tenth of it), so only the draw being a mass is checked (TEST.286).
    assert bh.mass_class == "supermassive" and 0 < bh.mass_solar < float("inf")
    assert bh.type == "Supermassive Black Hole"
    assert bh.galactic_orbital_period_gy is None and bh.galactic_orbital_speed_kms is None
    assert bh.has_accretion_disk
    eddington = tuning.EDDINGTON_LUMINOSITY_W_PER_SOLAR_MASS * bh.mass_solar
    assert 0 < bh.luminosity <= tuning.BLACK_HOLE_SUPERMASSIVE_EDDINGTON_RATIO_RANGE[1] * eddington
    # Sphere of influence G*M/sigma^2, sigma from the M-sigma relation for its mass (GEN.402).
    sigma = galaxyStructure.black_hole_dispersion_kms(bh.mass_solar) * 1000
    assert bh.system_perimeter == pytest.approx(constants.G * bh.mass / sigma ** 2 / constants.AU_TO_M)
    text = render_support.prose_text(render_support.phenomenon_section(bh))
    assert "supermassive black hole at the centre of the galaxy" in text
    rebuilt = BlackHole.from_dict(bh.to_dict(), make_config())
    assert rebuilt.mass_class == "supermassive"
    with pytest.raises(ValueError):
        BlackHole(make_config(), mass_class="giant")


