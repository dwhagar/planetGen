@pytest.mark.parametrize("cls", [BlackHole, NeutronStar] + STANDALONE_PHENOMENON_CLASSES)
def test_galactic_orbital_fields_are_well_formed(cls):
    # Every phenomenon (compact remnant or standalone) shares this
    # quartet -- see nebulaData.Nebula's `galactic_orbital_*` docstring
    # and utils.generate_galactic_orbit_fields.
    for _ in range(TRIALS):
        obj = cls(make_config())
        assert math.isfinite(obj.galactic_orbital_speed_kms) and obj.galactic_orbital_speed_kms > 0
        assert math.isfinite(obj.galactic_orbital_period_gy) and obj.galactic_orbital_period_gy > 0
        assert math.isfinite(obj.galactic_orbital_phase_deg) and 0 <= obj.galactic_orbital_phase_deg < 360
        assert math.isfinite(obj.galactic_min_update_interval_years) and obj.galactic_min_update_interval_years > 0


