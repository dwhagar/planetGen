def test_supernova_remnant_round_trip_preserves_embedded_compact_remnant():
    cfg = make_config()
    # Force a core-collapse progenitor with a visible remnant by retrying
    # generation until one comes out -- these are probabilistic, not
    # guaranteed on a single roll.
    for _ in range(50):
        remnant = SupernovaRemnant(cfg)
        if remnant.compact_remnant is not None:
            break
    else:
        pytest.fail("could not generate a supernova remnant with a visible compact remnant")

    reloaded = SupernovaRemnant.from_dict(remnant.to_dict(), cfg)
    assert type(reloaded.compact_remnant) is type(remnant.compact_remnant)
    assert reloaded.compact_remnant.name == remnant.compact_remnant.name
    assert render_support.phenomenon_section(reloaded) == render_support.phenomenon_section(remnant)


