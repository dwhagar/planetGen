def test_star_system_anchored_by_black_hole_skips_binary_generation():
    cfg = make_config(BINARY_SYSTEM=True)  # would force a binary for a normal Star
    bh = BlackHole(cfg)
    system = StarSystem(system_config=cfg, compact_remnant=bh)
    assert system.star is bh
    assert system.primary_star is bh
    assert system.binary_type is None
    assert system.wide_binary is None
    assert system.stars == [bh]


def test_star_system_anchored_by_neutron_star_can_force_planets():
    cfg = make_config(NUM_ORBITS=2)
    ns = NeutronStar(cfg)
    system = StarSystem(system_config=cfg, compact_remnant=ns)
    assert system.star is ns
    assert system.planet_count + system.belt_count == 2
    # A dark remnant's zero/near-zero luminosity means no real habitable
    # zone -- adjust_age_for_planets and rendering must not crash even
    # though every placed body is far outside any thermal comfort zone.
    assert str(system)


def test_star_system_anchored_by_black_hole_defaults_to_no_planets():
    # Disk-physics-driven generation (StarSystem._estimate_max_objects_from_disk_physics)
    # is snow-line-driven, which naturally collapses to zero for a
    # zero-luminosity remnant -- the real-world rarity of confirmed
    # planets around black holes falls out of the existing physics model
    # rather than needing a special case.
    # Seeded so it always draws a disk-less black hole (about 1 in 10 has
    # an accretion disk; this used to skip on those draws).
    cfg = make_config()
    with deterministic_entropy(0):
        bh = BlackHole(cfg)
        assert not bh.has_accretion_disk
        system = StarSystem(system_config=cfg, compact_remnant=bh)
    assert system.planet_count == 0
    assert system.belt_count == 0


