# planetgen/galaxy/mass_chain.py

"""
The galaxy's mass chain (GEN.400; docs/design/galaxy/intergalactic-and-halo-contents.md, section 5.13, rows 1 to 3).

One root draw and two links, all from the galaxy seed, with no Milky Way value anywhere:

1. The stellar mass `M*` is drawn from the galaxy stellar mass function, a double Schechter function (Baldry et al.
   2012, [R0238: Eq. 6], with the density per dex `ln(10) x exp(-x) [phi1 x^alpha1 + phi2 x^alpha2]`,
   `x = M / M*` of the function), by the inverse of its cumulative sum over the Auto window (`AUTO_LOG_MASS_RANGE`).
2. The halo mass `Mh` (200 times the critical density; Moster et al. measure theirs the same way) comes from the
   median stellar-to-halo relation of [R3181] ([R3181: Eq. 2] and Table 1, z = 0) and
   the halo mass function (`halo_function`, GEN.1154), by the conditional below.
3. The virial radius `r200` follows from `Mh` and the critical density, and the NFW concentration `c200` from
   [R1200: Eq. 8] with their 0.11 dex scatter.

**The halo of a given stellar mass.** The relation's scatter is 0.15 dex in `M*` at fixed `Mh`. The chain draws `M*`
first, so the halos that hold a galaxy of that mass are the halo mass function times that log-normal, `P(Mh | M*)`
proportional to `n(Mh) x LogNormal(log M*; log m*(Mh), 0.15)` (`halo_function.halo_log_mass_at`), and the halo is the
point of its cumulative distribution that a uniform draw from the seed picks. The first build (GEN.368) inverted the
median and put a Gaussian in `log Mh` about it; that is within 0.03 dex of this up to 3e10 solar masses of stars and up
to 0.34 dex too heavy at 2e11 (GEN.399).

**One cosmology.** [R3542] = 0.671 and Omega_m = 0.3175 (`halo_function` holds them with sigma_8, n_s and
Omega_b h^2) for the critical density, the concentration's `h` and the halo mass function. Moster's relation is quoted
for WMAP7 (h = 0.704) in solar masses; its halo masses are used as printed against the Planck halo function, a small
offset (stand-in HF3).

Every scatter is a log-normal about the median law, drawn through the one random wrapper
(`planetgen.util.draw.Stream`) from `unit_seed(galaxy_seed, "mass-chain", <link>)`, so one seed gives one galaxy and
two seeds give two.
"""

import dataclasses
import functools
import math

from planetgen.galaxy import dials
from planetgen.galaxy import halo_function
from planetgen.galaxy import seed as galaxySeed
from planetgen.physics import constants
from planetgen.util import draw
from planetgen.physics import unit_registry as units

_msun_to_kg = units.converter("Msun", "kg")

_kpc_to_m = units.converter("kpc", "m")

FALLBACK_SEED = bytes(16)
"""bytes: The seed of work that has no galaxy (a sector generated by the stand-alone command, a test), the one the
nebula and superbubble fields use too. It is a seed, not a Milky Way: it draws its own galaxy like any other."""

# --- Row 1: the stellar mass function ([R0238: Eq. 6], Table 1) ---------------------------------------

LOG_M_CHARACTERISTIC = 10.66
"""float: log10 of the function's characteristic mass M*, solar masses (h = 0.7, Chabrier IMF)."""
PHI_1 = 3.96e-3
ALPHA_1 = -0.35
PHI_2 = 0.79e-3
ALPHA_2 = -1.47

AUTO_LOG_MASS_RANGE = (math.log10(3.0e9), math.log10(6.0e9))
"""tuple: The stellar masses a galaxy with no pinned mass is drawn from, log10 solar masses: the lower edge of the first
family (3e9, Boss, 2026-10-16, 9:39 PM EDT) up to a factor of two above it, so the thin disc's scale length is about
1.3 to 1.5 kpc, roughly half that of a large spiral (Boss, 2026-10-21, 6:57 and 7:05 PM EDT: the sliders default to a
smaller spiral, the user pushes up). A pinned mass is not limited to it (`dials` gates it)."""

_GRID_STEPS = 4000
"""int: Steps of the grid the inverse cumulative sum is built on, about 0.00046 dex each."""

# --- Row 2: the stellar-to-halo relation ([R3181: Eq. 2], Table 1, z = 0) ---------------------

LOG_M1 = 11.590
N_NORM = 0.0351
BETA = 1.376
GAMMA = 0.608
STELLAR_SCATTER_DEX = 0.15
"""float: The relation's scatter, dex in M* at fixed Mh (constant)."""

# --- Row 3: the virial radius and the concentration (Planck-like cosmology; [R1200: Eq. 8]) --------

HUBBLE_H = halo_function.HUBBLE_H
OMEGA_MATTER = halo_function.OMEGA_MATTER
"""float: The matter density parameter; kept with `HUBBLE_H` as the one cosmology the chain states."""
OVERDENSITY = 200.0
"""float: The halo mass and radius are measured inside this many times the critical density (Moster's masses and
Dutton and Maccio's concentrations are both 200c, so no conversion is needed)."""
HALO_DELTA = OVERDENSITY / OMEGA_MATTER
"""float: `OVERDENSITY` times the critical density as a multiple of the mean matter density, which [R4367] use."""
CONCENTRATION_SCATTER_DEX = 0.11

_KPC_M = _kpc_to_m(1.0)
_MPC_M = _KPC_M * 1000.0
_H0_PER_S = 100.0 * HUBBLE_H * 1000.0 / _MPC_M
CRITICAL_DENSITY_KG_M3 = 3.0 * _H0_PER_S ** 2 / (8.0 * math.pi * constants.G)
"""float: The critical density today, kg per cubic metre."""


@dataclasses.dataclass(frozen=True)
class MassChain:
    """What one galaxy seed draws: the stellar mass, the halo mass, the virial radius and the concentration. A galaxy
    too light for a halo (`has_halo`) has the stellar mass only: the other three are `None`."""

    stellar_mass_solar: float
    halo_mass_solar: float
    virial_radius_kpc: float
    concentration: float


def stellar_mass_density_per_dex(log_mass):
    """[R0238]'s double Schechter function, galaxies per cubic megaparsec per dex of stellar mass, at
    `log_mass` (log10 solar masses)."""
    x = 10.0 ** (log_mass - LOG_M_CHARACTERISTIC)
    return math.log(10.0) * x * math.exp(-x) * (PHI_1 * x ** ALPHA_1 + PHI_2 * x ** ALPHA_2)


@functools.lru_cache(maxsize=4)
def _mass_cdf(log_range=AUTO_LOG_MASS_RANGE):
    """`(grid of log10 masses, cumulative share at each)` over `log_range` (the Auto window), by the trapezoid rule."""
    low, high = log_range
    step = (high - low) / _GRID_STEPS
    grid = [low + step * i for i in range(_GRID_STEPS + 1)]
    density = [stellar_mass_density_per_dex(point) for point in grid]
    cumulative = [0.0]
    for i in range(1, len(grid)):
        cumulative.append(cumulative[-1] + 0.5 * (density[i - 1] + density[i]) * step)
    total = cumulative[-1]
    return tuple(grid), tuple(value / total for value in cumulative)


def log_stellar_mass_at(share, log_range=AUTO_LOG_MASS_RANGE):
    """log10 of the stellar mass below which `share` (0 to 1) of the galaxies of `log_range` (the Auto window) lie, the
    inverse of the mass function's cumulative sum (linear between grid points)."""
    grid, cumulative = _mass_cdf(log_range)
    share = min(max(share, 0.0), 1.0)
    low, high = 0, len(cumulative) - 1
    while high - low > 1:
        middle = (low + high) // 2
        if cumulative[middle] <= share:
            low = middle
        else:
            high = middle
    span = cumulative[high] - cumulative[low]
    fraction = 0.0 if span <= 0.0 else (share - cumulative[low]) / span
    return grid[low] + fraction * (grid[high] - grid[low])


def stellar_to_halo_ratio(halo_mass_solar):
    """[R3181]'s median `M* / Mh` at z = 0 for a halo of `halo_mass_solar`."""
    m1 = 10.0 ** LOG_M1
    r = halo_mass_solar / m1
    return 2.0 * N_NORM / (r ** -BETA + r ** GAMMA)


def median_stellar_mass(halo_mass_solar):
    """The median stellar mass, solar masses, of a halo of `halo_mass_solar`. [Stand-in HF3, tier T1, tweak L1: the
    relation is [R3181]'s, fitted in a WMAP7 cosmology and read against the Planck halo mass function.]"""
    return halo_mass_solar * stellar_to_halo_ratio(halo_mass_solar)


HALO_MIN_STELLAR_MASS_SOLAR = median_stellar_mass(dials.HALO_MIN_HALO_MASS_SOLAR)
"""float: The median stellar mass of a halo of `dials.HALO_MIN_HALO_MASS_SOLAR`, about 4.6e6 solar masses: a galaxy
lighter than this has no halo (`has_halo`)."""


@functools.lru_cache(maxsize=1)
def _log_median_stellar_grid():
    return tuple(math.log10(median_stellar_mass(10.0 ** g)) for g in halo_function.grid_log_masses())


def conditional_halo_mass(stellar_mass_solar, share):
    """The halo mass, solar masses, below which a fraction `share` of the halos that hold `stellar_mass_solar` of stars
    lie: the quantile of `P(Mh | M*)` (see the module note).

    Raises:
        ValueError: If the stellar mass lies outside what halos of 1e8 to 1e17 solar masses hold.
    """
    target = math.log10(stellar_mass_solar)
    if not math.log10(median_stellar_mass(1.0e8)) <= target <= math.log10(median_stellar_mass(1.0e17)):
        raise ValueError(f"no halo of 1e8 to 1e17 solar masses holds {stellar_mass_solar:.3g} solar masses of stars")
    return 10.0 ** halo_function.halo_log_mass_at(target, share, _log_median_stellar_grid(), STELLAR_SCATTER_DEX,
                                                  HALO_DELTA)


def median_halo_mass(stellar_mass_solar):
    """The median halo mass, solar masses, of the galaxies that hold `stellar_mass_solar` of stars (the middle of
    `conditional_halo_mass`).

    Raises:
        ValueError: If the stellar mass lies outside what halos of 1e8 to 1e17 solar masses hold.
    """
    return conditional_halo_mass(stellar_mass_solar, 0.5)


def virial_radius_kpc(halo_mass_solar):
    """The radius, kpc, inside which the mean density is `OVERDENSITY` times the critical density."""
    mass_kg = _msun_to_kg(halo_mass_solar)
    radius_m = (3.0 * mass_kg / (4.0 * math.pi * OVERDENSITY * CRITICAL_DENSITY_KG_M3)) ** (1.0 / 3.0)
    return radius_m / _KPC_M


def median_concentration(halo_mass_solar):
    """[R1200: Eq. 8] for relaxed halos at z = 0: `c200 = 10^(0.905 - 0.101 log10(M200 h / 1e12))`."""
    return 10.0 ** (0.905 - 0.101 * math.log10(halo_mass_solar * HUBBLE_H / 1.0e12))


def has_halo(stellar_mass_solar):
    """Whether a galaxy of this stellar mass has a halo: it is at least the stellar mass the relation puts in a halo of
    `dials.HALO_MIN_HALO_MASS_SOLAR` (`HALO_MIN_STELLAR_MASS_SOLAR`). Under it no halo is drawn and no law that reads one runs (Boss, 7:33 PM EDT
    10-21)."""
    return stellar_mass_solar >= HALO_MIN_STELLAR_MASS_SOLAR


def has_full_structure(stellar_mass_solar):
    """Whether a galaxy of this stellar mass has a thick disc, a bar, a stellar halo and nuclear structures
    (`dials.FULL_STRUCTURE_MIN_STELLAR_MASS_SOLAR`); under it the galaxy is one disc plus a bulge."""
    return stellar_mass_solar >= dials.FULL_STRUCTURE_MIN_STELLAR_MASS_SOLAR


def _stream(galaxy_seed, link):
    return draw.Stream(galaxySeed.unit_seed(galaxy_seed or FALLBACK_SEED, "mass-chain", link))


def chain_from_stellar_mass(stellar_mass_solar, galaxy_seed, halo_mass_solar=None):
    """The halo, radius and concentration for a given stellar mass, their scatters drawn from `galaxy_seed`; none of
    them, and no halo function, for a galaxy under the halo threshold (`has_halo`). A `halo_mass_solar` the caller
    pinned (the Halo dial, GEN.606) replaces the halo mass draw only: the radius follows it and the concentration keeps
    the seed's own residual about the law at that mass.

    Raises:
        ValueError: For a pinned halo mass on a galaxy under the halo threshold.
    """
    if not has_halo(stellar_mass_solar):
        if halo_mass_solar is not None:
            raise ValueError(f"a galaxy of {stellar_mass_solar:.3g} solar masses of stars has no halo to pin "
                             f"(under {HALO_MIN_STELLAR_MASS_SOLAR:.3g})")
        return MassChain(stellar_mass_solar, None, None, None)
    if halo_mass_solar is None:
        halo = conditional_halo_mass(stellar_mass_solar, _stream(galaxy_seed, "halo-mass").random())
    else:
        halo = float(halo_mass_solar)
    log_c = math.log10(median_concentration(halo)) + _stream(galaxy_seed, "concentration").gauss(
        0.0, CONCENTRATION_SCATTER_DEX)
    return MassChain(stellar_mass_solar, halo, virial_radius_kpc(halo), 10.0 ** log_c)


@functools.lru_cache(maxsize=64)
def _draw_cached(galaxy_seed):
    share = _stream(galaxy_seed, "stellar-mass").random()
    return chain_from_stellar_mass(10.0 ** log_stellar_mass_at(share), galaxy_seed)


@functools.lru_cache(maxsize=64)
def _pinned_cached(galaxy_seed, stellar_mass_solar, halo_mass_solar):
    return chain_from_stellar_mass(stellar_mass_solar, galaxy_seed, halo_mass_solar)


def draw_mass_chain(galaxy_seed, stellar_mass_solar=None, halo_mass_solar=None):
    """
    The mass chain of a galaxy: the same seed gives the same chain.

    Args:
        galaxy_seed (bytes or None): The galaxy's 16-byte seed; `None` (work with no galaxy) uses `FALLBACK_SEED`.
        stellar_mass_solar (float, optional): A stellar mass the caller pinned (the Scale dial's mass, GEN.603): it
            replaces only the root draw, and the halo and concentration scatters are the seed's own, so the same seed
            at a new mass has the same residuals.
        halo_mass_solar (float, optional): A halo mass the caller pinned (the Halo dial, GEN.606): it replaces only the
            halo mass draw.

    Returns:
        MassChain: `stellar_mass_solar` inside the Auto window (or the pinned one), then the halo mass,
        virial radius and concentration it draws.

    Raises:
        ValueError: If a pinned mass is one no halo of 1e8 to 1e17 solar masses holds (`conditional_halo_mass`); a mass under
            `HALO_MIN_STELLAR_MASS_SOLAR` has no halo and does not reach it.
    """
    seed = bytes(galaxy_seed) if galaxy_seed else FALLBACK_SEED
    if stellar_mass_solar is None and halo_mass_solar is None:
        return _draw_cached(seed)
    if stellar_mass_solar is None:
        stellar_mass_solar = _draw_cached(seed).stellar_mass_solar
    return _pinned_cached(seed, float(stellar_mass_solar), None if halo_mass_solar is None else float(halo_mass_solar))
