# planetgen/galaxy/mass_chain.py

"""
The galaxy's mass chain (GEN.400; docs/design/intergalactic-and-halo-contents.md, section 5.13, rows 1 to 3).

One root draw and two links, all from the galaxy seed, with no Milky Way value anywhere:

1. The stellar mass `M*` is drawn from the galaxy stellar mass function, a double Schechter function (Baldry et al.
   2012, arXiv:1111.5707, Eq. 6, with the density per dex `ln(10) x exp(-x) [phi1 x^alpha1 + phi2 x^alpha2]`,
   `x = M / M*` of the function), by the inverse of its cumulative sum over the first family's range.
2. The halo mass `Mh` (200 times the critical density) is the median stellar-to-halo relation of Moster, Naab and
   White 2013 (arXiv:1205.5807, Eq. 2 and Table 1, z = 0) inverted numerically, with a log-normal draw about it.
3. The virial radius `r200` follows from `Mh` and the critical density, and the NFW concentration `c200` from
   Dutton and Maccio 2014 (arXiv:1402.7073, Eq. 8) with their 0.11 dex scatter.

**The approximation, and what it biases.** The relation's scatter is 0.15 dex in `M*` at fixed `Mh`. The chain draws
`M*` first, so the true `P(Mh | M*)` is the halo mass function times that log-normal, which is not the inverse of the
median with a scatter in `Mh`. This build uses the approximation Boss chose (2026-10-16, 10:11 PM EDT, "Approximate
now"): the median inverse with an effective scatter in `log Mh` of `0.15 / (d log M* / d log Mh)` at the median. It
biases the typical `Mh` at fixed `M*` low, because a steep halo mass function weights the heavy side more; GEN.399
(8.2) finds the halo mass function and compares.

**One cosmology.** Planck-like, h = 0.671 and Omega_m = 0.3175 (the table's choice) for the critical density and the
concentration's `h`. Moster's relation is quoted for WMAP7 (h = 0.704) in solar masses; its halo masses are used as
printed, a small offset the approximation absorbs.

Every scatter is a log-normal about the median law, drawn through the one random wrapper
(`planetgen.util.draw.Stream`) from `unit_seed(galaxy_seed, "mass-chain", <link>)`, so one seed gives one galaxy and
two seeds give two.
"""

import dataclasses
import functools
import math

from planetgen.galaxy import seed as galaxySeed
from planetgen.physics import constants
from planetgen.util import draw

FALLBACK_SEED = bytes(16)
"""bytes: The seed of work that has no galaxy (a sector generated by the stand-alone command, a test), the one the
nebula and superbubble fields use too. It is a seed, not a Milky Way: it draws its own galaxy like any other."""

# --- Row 1: the stellar mass function (Baldry et al. 2012, Eq. 6, Table 1) ---------------------------------------

LOG_M_CHARACTERISTIC = 10.66
"""float: log10 of the function's characteristic mass M*, solar masses (h = 0.7, Chabrier IMF)."""
PHI_1 = 3.96e-3
ALPHA_1 = -0.35
PHI_2 = 0.79e-3
ALPHA_2 = -1.47

FIRST_FAMILY_LOG_MASS_RANGE = (math.log10(3.0e9), math.log10(2.0e11))
"""tuple: The stellar masses the first family covers, log10 solar masses (Boss, 2026-10-16, 9:39 PM EDT)."""

_GRID_STEPS = 4000
"""int: Steps of the grid the inverse cumulative sum is built on, about 0.00046 dex each."""

# --- Row 2: the stellar-to-halo relation (Moster, Naab and White 2013, Eq. 2, Table 1, z = 0) ---------------------

LOG_M1 = 11.590
N_NORM = 0.0351
BETA = 1.376
GAMMA = 0.608
STELLAR_SCATTER_DEX = 0.15
"""float: The relation's scatter, dex in M* at fixed Mh (constant)."""

# --- Row 3: the virial radius and the concentration (Planck-like cosmology; Dutton and Maccio 2014, Eq. 8) --------

HUBBLE_H = 0.671
OMEGA_MATTER = 0.3175
"""float: The matter density parameter; kept with `HUBBLE_H` as the one cosmology the chain states."""
OVERDENSITY = 200.0
"""float: The halo mass and radius are measured inside this many times the critical density (Moster's masses and
Dutton and Maccio's concentrations are both 200c, so no conversion is needed)."""
CONCENTRATION_SCATTER_DEX = 0.11

_KPC_M = constants.PARSEC_M * 1000.0
_MPC_M = _KPC_M * 1000.0
_H0_PER_S = 100.0 * HUBBLE_H * 1000.0 / _MPC_M
CRITICAL_DENSITY_KG_M3 = 3.0 * _H0_PER_S ** 2 / (8.0 * math.pi * constants.G)
"""float: The critical density today, kg per cubic metre."""


@dataclasses.dataclass(frozen=True)
class MassChain:
    """What one galaxy seed draws: the stellar mass, the halo mass, the virial radius and the concentration."""

    stellar_mass_solar: float
    halo_mass_solar: float
    virial_radius_kpc: float
    concentration: float

    @property
    def halo_mass_kg(self):
        """float: The halo (virial) mass in kilograms: the central mass of the galaxy's tidal field (Hill spheres)."""
        return self.halo_mass_solar * constants.SOLAR_MASS_TO_KG


def stellar_mass_density_per_dex(log_mass):
    """Baldry et al. 2012's double Schechter function, galaxies per cubic megaparsec per dex of stellar mass, at
    `log_mass` (log10 solar masses)."""
    x = 10.0 ** (log_mass - LOG_M_CHARACTERISTIC)
    return math.log(10.0) * x * math.exp(-x) * (PHI_1 * x ** ALPHA_1 + PHI_2 * x ** ALPHA_2)


@functools.lru_cache(maxsize=1)
def _mass_cdf():
    """`(grid of log10 masses, cumulative share at each)` over the first family's range, by the trapezoid rule."""
    low, high = FIRST_FAMILY_LOG_MASS_RANGE
    step = (high - low) / _GRID_STEPS
    grid = [low + step * i for i in range(_GRID_STEPS + 1)]
    density = [stellar_mass_density_per_dex(point) for point in grid]
    cumulative = [0.0]
    for i in range(1, len(grid)):
        cumulative.append(cumulative[-1] + 0.5 * (density[i - 1] + density[i]) * step)
    total = cumulative[-1]
    return tuple(grid), tuple(value / total for value in cumulative)


def log_stellar_mass_at(share):
    """log10 of the stellar mass below which `share` (0 to 1) of the first family's galaxies lie, the inverse of the
    mass function's cumulative sum (linear between grid points)."""
    grid, cumulative = _mass_cdf()
    share = min(max(share, 0.0), 1.0)
    low, high = 0, len(cumulative) - 1
    while high - low > 1:
        middle = (low + high) // 2
        if cumulative[middle] <= share:
            low = middle
        else:
            high = middle
    span = cumulative[high] - cumulative[low]
    fraction = 0.0 if span <= 0.0 else (share - cumulative[low]) / span
    return grid[low] + fraction * (grid[high] - grid[low])


def stellar_to_halo_ratio(halo_mass_solar):
    """Moster, Naab and White 2013's median `M* / Mh` at z = 0 for a halo of `halo_mass_solar`."""
    m1 = 10.0 ** LOG_M1
    r = halo_mass_solar / m1
    return 2.0 * N_NORM / (r ** -BETA + r ** GAMMA)


def median_stellar_mass(halo_mass_solar):
    """The median stellar mass, solar masses, of a halo of `halo_mass_solar`."""
    return halo_mass_solar * stellar_to_halo_ratio(halo_mass_solar)


def median_halo_mass(stellar_mass_solar):
    """The halo mass whose median stellar mass is `stellar_mass_solar`: the relation inverted by bisection in log
    space (it is monotonic: the slope `d log M* / d log Mh` runs from 1 + beta at low mass to 1 - gamma at high mass).

    Raises:
        ValueError: If the stellar mass lies outside what halos of 1e8 to 1e17 solar masses hold.
    """
    low, high = 8.0, 17.0
    target = math.log10(stellar_mass_solar)
    if not math.log10(median_stellar_mass(10.0 ** low)) <= target <= math.log10(median_stellar_mass(10.0 ** high)):
        raise ValueError(f"no halo of 1e8 to 1e17 solar masses holds {stellar_mass_solar:.3g} solar masses of stars")
    for _ in range(60):
        middle = 0.5 * (low + high)
        if math.log10(median_stellar_mass(10.0 ** middle)) < target:
            low = middle
        else:
            high = middle
    return 10.0 ** (0.5 * (low + high))


def stellar_halo_slope(halo_mass_solar):
    """`d log M* / d log Mh` of the median relation at `halo_mass_solar`, by a central difference of 0.01 dex."""
    log_mass = math.log10(halo_mass_solar)
    step = 0.01
    above = math.log10(median_stellar_mass(10.0 ** (log_mass + step)))
    below = math.log10(median_stellar_mass(10.0 ** (log_mass - step)))
    return (above - below) / (2.0 * step)


def effective_halo_scatter_dex(halo_mass_solar):
    """The approximation's scatter in `log Mh` at a stellar mass: the relation's 0.15 dex in `log M*` over the slope."""
    return STELLAR_SCATTER_DEX / stellar_halo_slope(halo_mass_solar)


def virial_radius_kpc(halo_mass_solar):
    """The radius, kpc, inside which the mean density is `OVERDENSITY` times the critical density."""
    mass_kg = halo_mass_solar * constants.SOLAR_MASS_TO_KG
    radius_m = (3.0 * mass_kg / (4.0 * math.pi * OVERDENSITY * CRITICAL_DENSITY_KG_M3)) ** (1.0 / 3.0)
    return radius_m / _KPC_M


def median_concentration(halo_mass_solar):
    """Dutton and Maccio 2014 Eq. 8 for relaxed halos at z = 0: `c200 = 10^(0.905 - 0.101 log10(M200 h / 1e12))`."""
    return 10.0 ** (0.905 - 0.101 * math.log10(halo_mass_solar * HUBBLE_H / 1.0e12))


def _stream(galaxy_seed, link):
    return draw.Stream(galaxySeed.unit_seed(galaxy_seed or FALLBACK_SEED, "mass-chain", link))


def chain_from_stellar_mass(stellar_mass_solar, galaxy_seed):
    """The halo, radius and concentration for a given stellar mass, their scatters drawn from `galaxy_seed`."""
    median = median_halo_mass(stellar_mass_solar)
    scatter = effective_halo_scatter_dex(median)
    log_halo = math.log10(median) + _stream(galaxy_seed, "halo-mass").gauss(0.0, scatter)
    halo = 10.0 ** log_halo
    log_c = math.log10(median_concentration(halo)) + _stream(galaxy_seed, "concentration").gauss(
        0.0, CONCENTRATION_SCATTER_DEX)
    return MassChain(stellar_mass_solar, halo, virial_radius_kpc(halo), 10.0 ** log_c)


@functools.lru_cache(maxsize=64)
def _draw_cached(galaxy_seed):
    share = _stream(galaxy_seed, "stellar-mass").random()
    return chain_from_stellar_mass(10.0 ** log_stellar_mass_at(share), galaxy_seed)


def draw_mass_chain(galaxy_seed):
    """
    The mass chain of a galaxy: the same seed gives the same chain.

    Args:
        galaxy_seed (bytes or None): The galaxy's 16-byte seed; `None` (work with no galaxy) uses `FALLBACK_SEED`.

    Returns:
        MassChain: `stellar_mass_solar` inside the first family's range, then the halo mass, virial radius and
        concentration it draws.
    """
    return _draw_cached(bytes(galaxy_seed) if galaxy_seed else FALLBACK_SEED)


def current_central_mass_kg():
    """The central mass of the galaxy the running unit belongs to (`seed.current_galaxy_seed`), or of the fallback
    seed's galaxy outside any unit."""
    return central_mass_kg(galaxySeed.current_galaxy_seed())


def central_mass_kg(galaxy_seed):
    """The mass, kg, the galaxy's tidal field acts as if centred at its middle: the chain's virial mass, which every
    Hill sphere reads (until GEN.370 replaces it with the mass enclosed at the object's own radius)."""
    return draw_mass_chain(galaxy_seed).halo_mass_kg
