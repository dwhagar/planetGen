STAR_TYPE_PATTERN = re.compile(r"([OBAFGKM])([0-9])(IA\+|IAB|VII|III|IA|IB|II|IV|VI|0|V|D)")
"""A forced `SystemConfig.STAR_TYPE` (uppercased): spectral class, subclass
digit, Yerkes class. Always matched with `fullmatch` -- a prefix match
accepted 'G2Vjunk' as G2V and parsed 'G10V' as a G1 hypergiant ('0')."""


def _sample_hot_white_dwarf_mass_sol():
    """
    Draws the mass (solar masses) of a hot white dwarf, the exposed core of a
    planetary nebula (GEN.149): normal about `HOT_WHITE_DWARF_MEDIAN_MASS_SOL`,
    redrawn until it falls inside `HOT_WHITE_DWARF_MASS_RANGE_SOL`, so no
    pile-up appears at either end of the observed 0.5 to 0.7 Msun range.
    """
    low, high = constants.HOT_WHITE_DWARF_MASS_RANGE_SOL
    while True:
        mass_sol = draw.gauss(constants.HOT_WHITE_DWARF_MEDIAN_MASS_SOL, constants.HOT_WHITE_DWARF_MASS_SIGMA_SOL)
        if low <= mass_sol <= high:
            return mass_sol


@finite_domain()
def _sample_evolved_star_mass_sol(min_mass_sol, max_mass_sol):
    """
    Draws a progenitor mass (in solar masses) for an evolved-class star
    (giant, subgiant, bright giant, supergiant, or hypergiant) uniformly
    from `[min_mass_sol, max_mass_sol]`, rejecting and resampling any draw
    whose implied main-sequence lifespan
    (`ms_lifetime.lifetime_gy`, the same function
    `Star._calculate_initial_star_age_and_lifespan`'s evolved-star branch
    uses) would already exceed
    `tuning.UNIVERSE_AGE_GY` on its own.

    Such a mass could not actually have finished a main-sequence phase yet
    in the real universe, so a star with it could never legitimately be
    observed as an evolved class -- see "Evolved-star mass sampling can
    imply a pre-Big-Bang star" (formerly tracked in TODO.md). Rejecting and
    resampling (rather than clamping the draw up to the valid sub-range)
    keeps the accepted mass uniformly distributed over its valid portion
    instead of piling an artificial spike at the cutoff, matching the bias
    reasoning `spaceSector._random_point_in_annulus` documents for its own
    sampling. `tuning.EVOLVED_STAR_MASS_MAX_RESAMPLE_ATTEMPTS`
    caps the retries, mirroring `SpaceSector._random_position`'s own
    reject-and-resample loop, so a caller passing a range that's entirely
    invalid fails loudly with a `ValueError` instead of looping forever or
    silently returning a self-contradictory mass.

    Not used for Yerkes class VI (subdwarfs): their entire allowed mass
    range (0.1-0.8 Msun, see `constants.YERKES_MASS_CONSTRAINTS`)
    sits below the ~0.93 Msun cutoff, so every draw would be rejected. Real
    subdwarfs are thought to form via binary mass-stripping rather than
    single-star post-main-sequence evolution, so applying a single-star
    progenitor-lifespan check to their mass isn't physically appropriate
    anyway -- their age/lifespan is generated by an entirely separate,
    mass-independent path (`Star._calculate_initial_star_age_and_lifespan`'s
    Yerkes-VI branch) rather than this function's model, so the pre-Big-Bang
    issue this function guards against for other evolved classes doesn't
    apply to VI in the first place.

    Args:
        min_mass_sol (float): Lower bound of the class's allowed mass range,
                              in solar masses.
        max_mass_sol (float): Upper bound of the class's allowed mass range,
                              in solar masses.

    Returns:
        float: The accepted mass, in solar masses.

    Raises:
        ValueError: If no valid mass was found within
                   `tuning.EVOLVED_STAR_MASS_MAX_RESAMPLE_ATTEMPTS`
                   attempts.
    """
    for _ in range(tuning.EVOLVED_STAR_MASS_MAX_RESAMPLE_ATTEMPTS):
        mass_sol = draw.uniform(min_mass_sol, max_mass_sol)
        ms_lifespan = ms_lifetime.lifetime_gy(mass_sol)
        if ms_lifespan <= tuning.UNIVERSE_AGE_GY:
            return mass_sol

    raise ValueError(
        f"Could not sample a mass in [{min_mass_sol}, {max_mass_sol}] Msun whose implied "
        f"main-sequence lifespan doesn't exceed the age of the universe "
        f"({tuning.UNIVERSE_AGE_GY} Gyr) after "
        f"{tuning.EVOLVED_STAR_MASS_MAX_RESAMPLE_ATTEMPTS} attempts."
    )


def cloud_pressure_pa(density_cm3, temperature_k):
    """
    The pressure a nebula or supernova remnant's gas puts on a star's
    heliopause: ram pressure from the star moving through it at
    `constants.STAR_CLOUD_RELATIVE_SPEED_MS` plus thermal pressure.

    Args:
        density_cm3 (float): The cloud's hydrogen density (nH), per cm^3.
        temperature_k (float): The cloud's gas temperature in kelvin.

    Returns:
        float: The pressure in pascals.
    """
    n_m3 = max(density_cm3 or 0.0, 0.0) * constants.CM3_TO_M3
    rho = n_m3 * constants.ISM_MASS_PER_HYDROGEN * constants.HYDROGEN_ATOM_MASS_KG
    ram = rho * constants.STAR_CLOUD_RELATIVE_SPEED_MS ** 2
    thermal = n_m3 * constants.BOLTZMANN * max(temperature_k or 0.0, 0.0)
    return ram + thermal


def compressed_heliosphere_radius(radius_au, density_cm3, temperature_k):
    """
    A heliopause radius (computed against the open interstellar medium,
    `constants.ISM_PRESSURE`) pressed in by the cloud the star sits
    inside. The heliopause sits where the wind's momentum flux balances the
    outside pressure, so R scales as P^-1/2: a dense cold cloud (nH ~3,000
    cm^-3) shrinks the Sun's from ~85 AU to well under 1 AU. A cloud thinner
    than the open medium leaves it as it is.

    Args:
        radius_au (float): The open-space heliopause radius, AU.
        density_cm3 (float): The cloud's hydrogen density (nH), per cm^3.
        temperature_k (float): The cloud's gas temperature in kelvin.

    Returns:
        float: The compressed radius, AU.
    """
    pressure = max(cloud_pressure_pa(density_cm3, temperature_k), constants.ISM_PRESSURE)
    return radius_au * math.sqrt(constants.ISM_PRESSURE / pressure)


class Star(StellarObject):
    """
    Represents a single star, encapsulating its physical and orbital properties.

    This class orchestrates the procedural generation of a star, from its
    spectral type and luminosity to its mass and radius. It serves as the
    gravitational and energetic center of a `StarSystem`, defining the context
    for all orbiting planets and other celestial bodies.

    The generation process can be random or guided by specific parameters, such
    as forcing a large star or specifying a precise star type (e.g., 'G2V').
    Once the core properties are established, it calculates derived
    attributes, including the habitable zone, the system's gravitational
    perimeter, and the heliosphere's radius.

    Note: `self.type` here is a full descriptive string (e.g.
    "G2V Yellow Main Sequence Star"), unrelated in shape and purpose to
    `Planet.body_type`/`AsteroidBelt.body_type` (single-character 't'/'g'/'a'
    discriminators used to tell those two classes apart within `StarSystem`'s
    mixed `planets` list) -- the two just happen to share a common English
    word as their name.
    """

    def _calculate_initial_star_age_and_lifespan(self):
        """
        Calculates the star's initial age and lifespan, using a method that
        depends on its Yerkes luminosity class.

        For a main-sequence (Yerkes 'V') star, spectral letter fully
        determines both current temperature and total lifespan, so lifespan
        is drawn from `STAR_EVOLUTION`'s fixed per-letter range.

        For any evolved/remnant star other than a subdwarf (giants,
        subgiants, bright giants, supergiants, hypergiants), the current
        spectral letter reflects only present-day temperature -- an "M0III"
        red giant did not spend its life as an M-type star -- so
        `STAR_EVOLUTION` can't be used directly. Instead, the star's own
        already-generated mass is run through the same mass-luminosity-based
        main-sequence lifetime scaling used to derive that table, extended
        by the standard rule of thumb that ~90% of a star's total lifetime
        is spent on the main sequence; age is then drawn from the remaining
        post-main-sequence window (the star must already have completed its
        main-sequence phase to be observed in one of these classes).

        For subdwarfs (Yerkes 'VI'), that same mass-derived model doesn't
        apply: real subdwarfs are thought to form via binary mass-stripping
        rather than single-star post-main-sequence evolution, so this star's
        own (post-strip) mass has no direct relationship to a progenitor
        main-sequence lifespan the way it does for an ordinary giant. Age is
        instead drawn directly from a dedicated, old-population-biased
        range, and lifespan is that age plus a short remaining-phase window
        (see `tuning.SUBDWARF_*`) -- see this method's Yerkes-VI
        branch below for the full rationale.

        For white dwarfs, the lifespan is considered effectively infinite as
        they slowly cool, and age is instead drawn from a dedicated
        cooling-age range, since a white dwarf's spectral letter reflects its
        current temperature rather than a progenitor mass usable for either
        of the above.

        The initial age is randomly chosen to be a fraction of its total lifespan,
        ensuring the star is in a plausible evolutionary stage. This age can be
        further adjusted later by `adjust_age_for_planets` to accommodate the
        evolutionary requirements of its planets.

        Returns:
            tuple: A tuple containing:
                - age (float): The initial age of the star in billions of years (GY).
                - lifespan (float): The total expected lifespan of the star in
                                    billions of years (GY), or `float('inf')` for white dwarfs.
        """

        if self.yerkes_class in ["VII", "D"]:
            # A white dwarf's spectral letter encodes its *current* surface
            # temperature, not its progenitor's mass/spectral class, so it
            # can't be looked up in STAR_EVOLUTION's main-sequence lifespan
            # table (that would e.g. treat an "F5VII" white dwarf as if it
            # were an F-type main-sequence star with a ~4-9 Gy lifespan). A
            # white dwarf's remaining "lifespan" is effectively infinite --
            # it just cools for trillions of years -- so age is drawn from a
            # dedicated cooling-age range instead of a lifespan fraction.
            lifespan = float('inf')
            min_age = tuning.WHITE_DWARF_MIN_AGE_GY
            max_age = tuning.WHITE_DWARF_MAX_AGE_GY
            if self.system_config.AGE == "old":
                min_age = min_age + (max_age - min_age) * tuning.OLD_STAR_AGE_LIFESPAN_RATIO
            elif self.system_config.AGE == "young":
                max_age = max_age - (max_age - min_age) * (1 - tuning.YOUNG_STAR_AGE_LIFESPAN_RATIO)
            age = draw.uniform(min_age, max_age)
            return age, lifespan

        if self.yerkes_class == "VI":
            # Subdwarfs (real sdB/sdO stars) are thought to form via binary
            # mass-stripping near the tip of a lower/intermediate-mass
            # progenitor's red-giant branch, not ordinary single-star
            # post-main-sequence evolution -- so this star's own (post-strip)
            # mass has no direct relationship to its progenitor's actual
            # main-sequence lifespan the way it does for the generic
            # evolved-star branch below. Deriving age/lifespan from mass
            # the same way that branch does (as this class used to) is what
            # let a generated subdwarf's age come out older than the
            # universe -- generate_star's mass sampling deliberately draws
            # a subdwarf's mass uniformly across its whole allowed range
            # (see _sample_evolved_star_mass_sol's docstring), and most of
            # that range implies a main-sequence lifespan alone already
            # longer than the universe.
            #
            # Real subdwarf progenitors are typically old, low-mass
            # population stars -- a short-lived, higher-mass star wouldn't
            # have had time to reach the RGB tip and get stripped in the
            # first place -- so age is instead drawn directly from a
            # dedicated, old-population-biased range, independent of this
            # star's own mass. The core-helium-burning subdwarf phase itself
            # is short relative to that age (real sdB stars: roughly
            # 0.05-0.3 Gy), so lifespan is simply age plus a short
            # remaining-phase window rather than a separately-derived value.
            min_age = tuning.SUBDWARF_MIN_AGE_GY
            max_age = tuning.SUBDWARF_MAX_AGE_GY
            if self.system_config.AGE == "old":
                min_age = min_age + (max_age - min_age) * tuning.OLD_STAR_AGE_LIFESPAN_RATIO
            elif self.system_config.AGE == "young":
                max_age = max_age - (max_age - min_age) * (1 - tuning.YOUNG_STAR_AGE_LIFESPAN_RATIO)
            age = draw.uniform(min_age, max_age)
            lifespan = age + draw.uniform(
                tuning.SUBDWARF_REMAINING_PHASE_MIN_GY,
                tuning.SUBDWARF_REMAINING_PHASE_MAX_GY,
            )
            return age, lifespan

        if self.yerkes_class != "V":
            # Evolved-star track (giants, subgiants, bright giants,
            # supergiants, hypergiants -- subdwarfs (VI) and white dwarfs
            # (VII/D) are handled by their own branches above and never
            # reach here): the current spectral letter is just this star's
            # present temperature, not a main-sequence class it belongs to
            # -- an "M0III" red giant did not spend its whole life as an
            # M-type star. Derive the star's actual main-sequence lifespan
            # from its own already-generated mass instead, then extend it
            # for the (much shorter) post-main-sequence phase it's
            # currently in.
            mass_sol = self.mass / constants.SOLAR_MASS_TO_KG
            ms_lifespan = ms_lifetime.lifetime_gy(mass_sol)
            lifespan = ms_lifespan / tuning.MS_LIFESPAN_FRACTION_OF_TOTAL

            # The star must already have completed its main-sequence phase to
            # be observed as an evolved class, so age is drawn from the
            # (comparatively short) post-main-sequence window only.
            min_age = ms_lifespan
            max_age = lifespan
            if self.system_config.AGE == "old":
                min_age = min_age + (max_age - min_age) * tuning.OLD_STAR_AGE_LIFESPAN_RATIO
            elif self.system_config.AGE == "young":
                max_age = max_age - (max_age - min_age) * (1 - tuning.YOUNG_STAR_AGE_LIFESPAN_RATIO)

            # No star observed today can be older than the universe itself,
            # regardless of how long its class could theoretically keep
            # burning (see UNIVERSE_AGE_GY) -- but this star must also
            # already be at least as old as its own main-sequence lifespan
            # to be observed as an evolved class at all (min_age's floor).
            # `max(..., min_age)` applies the cosmological cap only when
            # it's actually compatible with that requirement, rather than
            # ever shrinking max_age below min_age (which would produce a
            # self-contradictory star -- e.g. a red giant younger than its
            # own progenitor's main-sequence lifespan). A sub-solar-mass
            # progenitor whose main-sequence lifespan alone already exceeds
            # the age of the universe can't be fixed by clamping age alone --
            # `generate_star`'s mass sampling (`_sample_evolved_star_mass_sol`)
            # now rejects and resamples such a mass before a star ever gets
            # this far, for every Yerkes class this branch handles, so
            # `min_age` staying above `UNIVERSE_AGE_GY` here should no longer
            # happen in practice; this `max(..., min_age)` is kept as a
            # defensive fallback rather than an assumption that `self.mass`
            # is always already valid.
            max_age = max(min(max_age, tuning.UNIVERSE_AGE_GY), min_age)
            age = draw.uniform(min_age, max_age)

            return age, lifespan

        spectral_class_char = self.type[0]
        star_info = tuning.STAR_EVOLUTION.get(spectral_class_char, {})

        min_lifespan, max_lifespan = star_info["lifespan_gy"]
        lifespan = draw.uniform(min_lifespan, max_lifespan)

        # MIN_INITIAL_STAR_AGE_GY is a sensible floor for long-lived stars (F/G/K/M),
        # but a fixed 100-million-year floor is nonsensical for a star whose entire
        # lifespan is shorter than that (O/B, and short-lived rolls of A) -- it would
        # make min_age exceed max_age below, silently discarding the young/old
        # request and any real age variance for those types. Scale it down for
        # short-lived stars so it never exceeds a small fraction of their own lifespan.
        min_age = min(tuning.MIN_INITIAL_STAR_AGE_GY,
                      lifespan * tuning.MIN_INITIAL_STAR_AGE_LIFESPAN_RATIO)
        max_age = lifespan * tuning.MAX_INITIAL_STAR_AGE_LIFESPAN_RATIO

        # Values are calculated to be either in last ratio of the
        # lifespan (i.e. the last 1/3 of the star's life or the
        # first 1/3 of a star's life).
        if self.system_config.AGE == "old":
            min_age = min_age + lifespan * tuning.OLD_STAR_AGE_LIFESPAN_RATIO
        elif self.system_config.AGE == "young":
            max_age = max_age - lifespan * (1 - tuning.YOUNG_STAR_AGE_LIFESPAN_RATIO)

        # No star observed today can be older than the universe itself,
        # regardless of how long its class could theoretically keep burning
        # (see UNIVERSE_AGE_GY) -- this is what actually keeps very
        # long-lived classes like M (lifespan_gy up to 5500 Gy) from rolling
        # an implausible "918 billion years old" age. Re-clamp min_age down
        # to the (possibly now-lower) max_age afterward so an "old" bias
        # never inverts the range for such a star.
        max_age = min(max_age, tuning.UNIVERSE_AGE_GY)
        min_age = min(min_age, max_age)

        age = draw.uniform(min_age, max_age) # Ensure age is less than lifespan

        return age, lifespan


    @staticmethod
    @finite_domain()
    def _calculate_heliosphere_radius_static(mass, luminosity, radius_km, star_type, yerkes_class):
        """
        Estimates the radius of the star's heliosphere (astrosphere).

        The heliosphere is a "bubble" in space created by the stellar wind, a
        stream of charged particles flowing from the star. The edge of this
        bubble, the heliopause, is where the stellar wind's pressure is balanced
        by the interstellar medium (ISM).

        This function employs a tiered approach to model the stellar wind's
        mass-loss rate and velocity, which are highly dependent on the star's
        evolutionary stage (Yerkes luminosity class) and spectral type. Three
        physical models are applied: the Nieuwenhuijzen & de Jager (1990)
        empirical mass-loss fit for every evolved star (giants through
        hypergiants), a radiation-driven-wind power law for hot O/B dwarfs,
        and an empirical coronal-wind scaling for cool main-sequence dwarfs
        (and white dwarfs) -- chosen to ensure physically plausible results
        across the stellar spectrum.

        The heliopause radius is then calculated based on the balance between
        the stellar wind's momentum flux and the pressure of the interstellar medium.

        Args:
            mass (float): The star's mass in kilograms.
            luminosity (float): The star's luminosity in Watts.
            radius_km (float): The star's radius in kilometers.
            star_type (str): The star's full spectral type string (e.g., 'G2V'),
                             whose first character (the spectral class) selects
                             between the hot-dwarf and cool-dwarf wind models
                             within the main-sequence tier.
            yerkes_class (str): The star's Yerkes luminosity class (e.g., 'V',
                                'III', '0'), which selects the wind/mass-loss model.

        Returns:
            float: The estimated radius of the heliosphere in Astronomical Units (AU).
        """
        # --- 1. Get Fundamental Stellar Properties (from arguments) ---
        radius_m = radius_km * constants.KM_TO_M_FACTOR  # Convert radius from km to meters
        lum_sol = luminosity / constants.SOLAR_LUMINOSITY
        mass_sol = mass / constants.SOLAR_MASS_TO_KG
        radius_sol = radius_m / constants.SOLAR_RADIUS_M
        spectral_class = star_type[0].upper() if star_type else None

        # --- 2. Calculate Mass-Loss Rate (M-dot) and Wind Velocity (v_inf) ---
        # A single formula for mass loss is insufficient. We use a tiered system based on
        # the star's Yerkes luminosity class (evolutionary stage) and spectral type.
        escape_velocity = math.sqrt(constants.ESCAPE_VELOCITY_CONSTANT * constants.G * mass / radius_m)


        # TIER 1: Evolved stars -- giants (III), subgiants (IV), bright giants
        # (II), supergiants (IB/IAB/IA/IA+), and hypergiants (0). These were
        # previously three separately hand-fit tiers (a hypergiant power-law,
        # plus Reimers' Law with two different eta values for "giants" vs
        # "supergiants") stitched together at Yerkes-class boundaries -- the
        # exact structure that let the old hypergiant constant drift ~9
        # orders of magnitude out of calibration unnoticed. Nieuwenhuijzen &
        # de Jager (1990) is a single empirical mass-loss fit spanning this
        # whole regime, so one formula and one continuous curve now covers
        # all of it (see constants.py for the correction applied
        # above its known high-luminosity overestimation threshold).
        if yerkes_class in ["0", "IA+", "IA", "IAB", "IB", "II", "III", "IV"]:
            mass_loss_rate_smyr = (constants.NDJ_MASS_LOSS_COEFFICIENT
                                   * (lum_sol**constants.NDJ_LUMINOSITY_EXPONENT)
                                   * (mass_sol**constants.NDJ_MASS_EXPONENT)
                                   * (radius_sol**constants.NDJ_RADIUS_EXPONENT))
            if lum_sol > constants.NDJ_HIGH_LUMINOSITY_THRESHOLD_LSUN:
                mass_loss_rate_smyr *= constants.NDJ_HIGH_LUMINOSITY_CORRECTION_FACTOR

            if yerkes_class == "0":
                # Hypergiant winds are an extreme multiple of escape velocity.
                wind_velocity = constants.HYPERGIANT_WIND_VELOCITY_FACTOR * escape_velocity
            else:
                # Wind velocity is a smaller fraction of escape velocity for these cooler giants/supergiants.
                wind_velocity = constants.GIANT_WIND_VELOCITY_FACTOR * escape_velocity

        # TIER 2a: Hot main-sequence dwarfs (O and B, Class V/VI)
        # Unlike cool dwarfs, O/B stars have powerful radiation-driven winds (line-driven,
        # via the same physical mechanism as hypergiants/supergiants, just far less extreme):
        # mass loss scales steeply with luminosity rather than the coronal/magnetic-activity
        # scaling used for cool dwarfs below. Without this tier, a hot O-type star would be
        # (incorrectly) modeled with a weaker wind than a cool, dim M dwarf.
        elif spectral_class in ("O", "B") and yerkes_class in ["V", "VI"]:
            mass_loss_rate_smyr = constants.OB_DWARF_MASS_LOSS_RATE_FACTOR * (lum_sol**constants.OB_DWARF_MASS_LOSS_RATE_EXPONENT)
            wind_velocity = constants.OB_DWARF_WIND_VELOCITY_FACTOR * escape_velocity

        # TIER 2b: Cool main-sequence dwarfs (A through M, Class V/VI) and White Dwarfs (VII)
        # For sun-like and cooler stars (plus stellar remnants), mass loss is very low. We
        # scale directly from the Sun's known properties for a stable, physically grounded result.
        else:
            # For cool main-sequence stars, mass loss is driven by magnetic activity, not
            # radiation pressure. The Reimers' law scaling (L*R/M) is inaccurate here.
            # We use a more modern, empirically-derived formula from Wood et al. (2005),
            # which relates mass-loss rate to surface X-ray flux.
            # M-dot ~ R^2 * F_x^1.34, and F_x ~ L^-0.5
            # This results in a scaling relationship of M-dot ~ R^2 * L^-0.5
            # We normalize this to the Sun's known mass-loss rate.
            # The mass term is added to account for gravitational binding.
            scaling_factor = (radius_sol**constants.RADIUS_SOL_EXPONENT) * (lum_sol**constants.LUMINOSITY_SOL_EXPONENT) * (mass_sol**constants.MASS_SOL_EXPONENT)
            mass_loss_rate_smyr = constants.SUN_MASS_LOSS_RATE_SOLAR_MASS_PER_YEAR * scaling_factor # 2e-14 is the Sun's M-dot in M_sol/yr

            # Scale wind velocity based on the star's escape velocity relative to the Sun's.
            wind_velocity = constants.SOLAR_WIND_VELOCITY * (escape_velocity / constants.SOLAR_ESCAPE_VELOCITY)

        # --- 3. Convert and Calculate Final Radius ---

        # Convert M-dot from (solar masses/year) to (kg/s)
        mass_loss_rate_kgs = mass_loss_rate_smyr * constants.SOLAR_MASS_TO_KG / constants.SECONDS_PER_YEAR

        # The heliopause radius is where the stellar wind's momentum flux balances the ISM pressure.
        # R = sqrt( (M-dot * v_inf) / (4 * pi * P_ism) )
        momentum_flux = max(mass_loss_rate_kgs * wind_velocity, constants.MIN_MOMENTUM_FLUX) # Ensure momentum_flux is not zero or negative

        try:
            heliopause_radius_m = math.sqrt(momentum_flux / (constants.FOUR_PI * constants.ISM_PRESSURE))
        except ValueError:
            # This should not happen with the floor value, but as a final safety net.
            heliopause_radius_m = constants.HELIOPAUSE_RADIUS_DEFAULT_M

        # Convert the final radius from meters to Astronomical Units (AU) for output.
        return heliopause_radius_m / constants.AU_TO_M

    def calculate_heliosphere(self):
        """
        Estimates the radius of the star's heliosphere (astrosphere) by
        delegating to the `_calculate_heliosphere_radius_static` helper with
        this star's own mass, luminosity, radius, type, and Yerkes class.

        Returns:
            float: The estimated radius of the heliosphere in Astronomical Units (AU).
        """
        return Star._calculate_heliosphere_radius_static(self.mass, self.luminosity, self.radius, self.type, self.yerkes_class)

    def __init__(self, system_config: SystemConfig, name=None, **kwargs):
        """
        Initializes a Star object, generating its properties based on specified constraints.

        This constructor orchestrates the creation of a star. It can generate a
        star randomly or be guided by specific parameters provided through the
        `config` module. The `config.STAR_TYPE` parameter allows for the creation
        of a star with a specific spectral class, subclass, and Yerkes
        classification (e.g., 'G2V'). If `config.LARGE_STAR` is True, this
        influences the star's initial generation to favor larger, more massive
        stars.

        If a `name` is provided, it will be used for the star; otherwise, a
        random name will be generated using `generate_phoneme_salad_name`.

        Once the core properties (`type`, `radius`, `mass`, `temperature`, `luminosity`)
        are established by `generate_star()`, this constructor calculates derived
        properties such as the `age`, `lifespan`, `habitable_zone`,
        `system_perimeter` (Hill sphere), and `heliosphere_radius`.

        Args:
            system_config (SystemConfig): The shared SystemConfig object for the system.
            name (str, optional): The name to assign to the star. If None, a
                                  random name will be generated. Defaults to None.

        Keyword Args:
            mass_override (float, optional): An explicit mass (kg) for
                secondary-star generation in binary systems.
            galactic_center_dist_ly (float, optional): This star's actual
                distance from the galactic center, in light-years, threaded
                into `calculate_system_perimeter` -- see that method's
                docstring. `None` (the default) uses the radius that holds half of the galaxy's disc stars (`galaxy.scales`).
            galactic_orbital_phase_deg (float, optional): This star's
                current angular position around its galactic orbit, in
                degrees -- the value `planetgen.db.store.advance_orbital_phases`
                advances over time, the same role `orbital_phase_deg` plays
                for a planet/moon's own orbit (see
                `physics.planets.generate_orbital_motion_properties`).
                `StarSystem.__init__` rolls this once per system and passes
                the *same* value to the primary star, the secondary star
                (if any), and the `BinaryStarProxy` -- a binary pair's
                negligible internal separation (AU) next to its galactic
                orbit radius (light-years) means both stars move around the
                galaxy together, not independently, so they must share one
                phase rather than each rolling their own. `None` (the
                default) rolls a fresh random value in `[0, 360)` -- the
                correct behavior for a standalone `Star` with no system
                threading this through.
        """
        super().__init__(system_config, name=name, galactic_center_dist_ly=kwargs.get('galactic_center_dist_ly'))

        self.luminosity = None
        self.temperature = None
        self.mass = None
        self.radius = None
        self.type = None
        self.yerkes_class = None
        self.habitable_zone = None
        self.system_perimeter = None
        self.heliosphere_radius = None
        self.galactic_orbital_speed_kms = None
        self.galactic_orbital_period_gy = None
        self.galactic_orbital_phase_deg = None
        self.galactic_min_update_interval_years = None
        # Added mass_override for secondary star generation in binary systems
        self.generate_star(mass_override=kwargs.get('mass_override'),
                           initial_mass_sol=kwargs.get('initial_mass_sol'),
                           age_gy=kwargs.get('age_gy'))
        self._finish_init(kwargs)

    def _finish_init(self, kwargs):
        """The derived properties every generated star gets once its core
        ones exist: age and lifespan (unless the population model already
        fixed them), habitable zone, Hill sphere, heliosphere and galactic
        orbit."""
        if self._model_age_lifespan is not None:
            self.age, self.lifespan = self._model_age_lifespan
        else:
            self.age, self.lifespan = self._calculate_initial_star_age_and_lifespan()
        self.habitable_zone = calculate_habitable_zone(self.luminosity)
        self.system_perimeter = self.calculate_system_perimeter(self.galactic_center_dist_ly)
        self.heliosphere_radius = self.calculate_heliosphere()
        self.set_galactic_motion(self.galactic_center_dist_ly, kwargs.get('galactic_orbital_phase_deg'))
        # GEN.104: the spin, last so nothing above draws differently.
        self.rotation_period_hours = spin.star_rotation_period_hours(
            self.mass, self.radius, self.temperature, self.age, self.yerkes_class)
        spin.set_spin(self, spin.GALACTIC_POLE, spin.rayleigh_tilt_deg())
        # GEN.86: coronal X-rays, XUV and flares, from mass and age.
        activity.generate_activity(self)
        # GEN.158: [Fe/H], from its own stream so no older draw moves.
        self.metallicity_fe_h = kwargs.get('metallicity_fe_h')
        if self.metallicity_fe_h is None:
            # A horizontal-branch star's [Fe/H] was drawn with its colour (GEN.286).
            self.metallicity_fe_h = self._model_fe_h
        if self.metallicity_fe_h is None:
            self.metallicity_fe_h = metallicity.sample_fe_h(
                getattr(self.system_config, "POPULATION", None),
                scales.default_galactocentric_ly() if self.galactic_center_dist_ly is None
                else self.galactic_center_dist_ly,
                draw.Stream(f"metallicity:{self.mass!r}:{self.age!r}:{self.galactic_center_dist_ly!r}"),
                peaks=getattr(self.system_config, "FE_H_PEAKS", None))
        # GEN.242: the disk of a young star, from its own stream like the [Fe/H] above.
        if self.yerkes_class in pre_main_sequence.STAGE_CLASSES:
            disk = pre_main_sequence.draw_disk(
                self.mass / constants.SOLAR_MASS_TO_KG, self.age * 1.0e9, self.luminosity / constants.SOLAR_LUMINOSITY,
                draw.Stream(f"disk:{self.mass!r}:{self.age!r}"))
            for name, value in (disk or {}).items():
                setattr(self, name, value)

    def _generate_from_population_model(self, initial_mass_sol=None, age_gy=None):
        """
        Sets this star's properties from the population model
        (`stellarEvolution`): a Kroupa-IMF mass and a star-formation-history
        age (or the given ones), evolved to its present state. The letter,
        subclass and Yerkes class follow from the resulting temperature and
        luminosity; the radius from Stefan-Boltzmann (a white dwarf's from
        its mass-radius relation). Also fixes `age`/`lifespan` (read by
        `__init__` instead of `_calculate_initial_star_age_and_lifespan`),
        `initial_mass_sol` (a binary secondary's mass is a fraction of it)
        and `phase_end_age_gy` (`adjust_age_for_planets` keeps the age
        inside the present phase).

        `+large_star` truncates the IMF at `LARGE_STAR_MIN_MASS_SOL`, and a
        primary that has already collapsed to a neutron star or black hole
        is redrawn (see `stellarEvolution.sample_living_star`). The config's
        `POPULATION` sets the age range and `MAX_STAR_LUMINOSITY_SOL` redraws
        any star at least that bright.
        """
        age_bias = self.system_config.AGE
        population = getattr(self.system_config, "POPULATION", None)
        fe_h_peaks = getattr(self.system_config, "FE_H_PEAKS", None)
        age_law = getattr(self.system_config, "AGE_LAW", None)
        state = None
        if initial_mass_sol is not None:
            initial_mass_sol = max(initial_mass_sol, tuning.IMF_BREAKS_SOL[0])
            age = age_gy if age_gy is not None else sample_star_age_gy(age_bias)
            state = evolve_star(initial_mass_sol, age, population=population, fe_h_peaks=fe_h_peaks)
            # A companion of a specified-type primary takes a fraction of
            # that star's present mass, which can be heavy enough to have
            # collapsed already at the pair's age. Lighten it until it is
            # alive rather than redraw it at another age: the pair shares
            # one age (GEN.53).
            while state is None and initial_mass_sol > tuning.IMF_BREAKS_SOL[0]:
                initial_mass_sol = max(initial_mass_sol * 0.8, tuning.IMF_BREAKS_SOL[0])
                state = evolve_star(initial_mass_sol, age, population=population, fe_h_peaks=fe_h_peaks)
        if state is None:
            # No companion given.
            habitable_host = self.system_config.HABITABLE_WORLD is True or self.system_config.INTELLIGENT_LIFE is True
            max_luminosity_sol = getattr(self.system_config, "MAX_STAR_LUMINOSITY_SOL", None)
            max_mass_sol = getattr(self.system_config, "MAX_STAR_MASS_SOL", None)
            try:
                initial_mass_sol, age, state = sample_living_star(
                    age_bias, self.system_config.LARGE_STAR, habitable_host=habitable_host,
                    population=population, max_luminosity_sol=max_luminosity_sol, max_mass_sol=max_mass_sol,
                    fe_h_peaks=fe_h_peaks, age_law=age_law)
            except ValueError:
                if not (self.system_config.LARGE_STAR and (max_luminosity_sol is not None
                                                           or max_mass_sol is not None)):
                    raise
                # A large star a run's prevalence asked for (GEN.52) can be
                # brighter, or heavier, than a sector whose bright and
                # massive stars were pre-placed allows; this one stays an
                # ordinary star.
                log.choice("Large star", "dropped", "none within the sector's star limits")
                initial_mass_sol, age, state = sample_living_star(
                    age_bias, None, habitable_host=habitable_host,
                    population=population, max_luminosity_sol=max_luminosity_sol, max_mass_sol=max_mass_sol,
                    fe_h_peaks=fe_h_peaks, age_law=age_law)

        self._apply_params(star_params(initial_mass_sol, age, state))
        log.choice("Star", self.type, f"population model: initial mass {initial_mass_sol:.3g} Msun, "
                                      f"age {age:.3g} Gyr")

    def _apply_params(self, params):
        """Sets this star's generated properties from a `star_params` dict
        (see `stellarEvolution.star_params`), rolling nothing."""
        self.type = params["type"]
        self.yerkes_class = params["yerkes_class"]
        self.radius = params["radius_km"]
        self.mass = params["mass_kg"]
        self.temperature = params["temperature_k"]
        self.luminosity = params["luminosity_w"]
        self.initial_mass_sol = params["initial_mass_sol"]
        self.phase_end_age_gy = params["phase_end_age_gy"]
        self._model_age_lifespan = (params["age_gy"], params["lifespan_gy"])
        self._model_fe_h = params.get("metallicity_fe_h")

    @classmethod
    def from_params(cls, params, system_config, name=None, **kwargs):
        """
        Builds a real `Star` from a `stellarEvolution.star_params` dict (a
        pre-placed bright star read back from storage, or a draw from
        `star_population`) without re-rolling any of its generated
        properties: only the derived ones (habitable zone, Hill sphere,
        heliosphere, galactic orbit) are computed, exactly as `__init__`
        computes them. Accepts `__init__`'s `galactic_center_dist_ly` and
        `galactic_orbital_phase_deg` keywords.
        """
        # GEN.158: a stored [Fe/H] is kept; none (or an old row) leaves the star to draw its own.
        if params.get("metallicity_fe_h") is not None:
            kwargs.setdefault("metallicity_fe_h", params["metallicity_fe_h"])
        star = cls.__new__(cls)
        StellarObject.__init__(star, system_config, name=name,
                               galactic_center_dist_ly=kwargs.get("galactic_center_dist_ly"))
        star._apply_params(params)
        star._finish_init(kwargs)
        return star

    def generate_star(self, mass_override=None, initial_mass_sol=None, age_gy=None):
        """
        Generates the physical properties of the star based on a hierarchical,
        physically-constrained procedural model.

        A random star (no `config.STAR_TYPE`) comes from the population
        model in `stellarEvolution.py`: see `_generate_from_population_model`.
        `initial_mass_sol`/`age_gy` pin that model's mass and age (a binary
        secondary: a fraction of the primary's initial mass, at the
        primary's age). The rest of this docstring describes the path for a
        specified `config.STAR_TYPE`; `mass_override` (kg) still forces a
        specified-type secondary's mass.

        The generation process is fundamentally different for user-specified stars
        (via `config.STAR_TYPE`) versus randomly generated ones.

        For specified stars (when `config.STAR_TYPE` is set):
        1.  **Parsing Input**: The method first parses the `config.STAR_TYPE` string
            (e.g., 'G2V') to extract the spectral class (O, B, A, F, G, K, M),
            subclass (0-9), and Yerkes luminosity class (e.g., V for Main Sequence).
            It raises a `ValueError` if the format is invalid.
        2.  **Temperature Calculation**: The star's surface temperature is calculated
            based on its spectral class and subclass, interpolating within the
            `TEMP_RANGES` data.
        3.  **Luminosity Determination**: A valid luminosity range is established
            by finding the *intersection* of the allowed luminosity ranges for
            both the spectral class (`SPECTRAL_LUMINOSITY_RANGES`) and the
            Yerkes class (`YERKES_LUMINOSITY_RANGES`). A random luminosity is
            then chosen from this overlapping range. Special handling is included
            for white dwarfs, which can have temporarily high luminosities.
        4.  **Mass Calculation**: The star's mass is determined based on the
            physical constraints defined for its Yerkes class in `YERKES_MASS_CONSTRAINTS`.
            For main-sequence stars, a mass-luminosity relation is used. For white
            dwarfs, an inverse mass-radius relation is considered, with mass
            constrained by the Chandrasekhar limit. For giants and supergiants,
            mass is randomly selected within their class-specific bounds.
        5.  **Radius Calculation**: The star's radius is calculated last. For white
            dwarfs, an inverse mass-radius relationship is applied. For all other
            star types, the Stefan-Boltzmann law is used, deriving radius from
            luminosity and temperature.

        For random stars (when `config.STAR_TYPE` is None):
        1.  **Spectral Class Selection**: A spectral class is chosen probabilistically
            based on their prevalence in the galactic population.
            `self.system_config.LARGE_STAR` being True biases this selection
            towards hotter, more massive stars.
        2.  **Luminosity Generation**: A luminosity is randomly chosen from the
            typical range for the selected spectral class.
        3.  **Yerkes Class Determination**: The Yerkes luminosity class (e.g.,
            Supergiant, Main Sequence, White Dwarf) is *derived* from the
            generated luminosity, using thresholds defined in `YERKES_LUMINOSITY_RANGES`.
        4.  **Temperature and Subclass Calculation**: The star's surface temperature
            is randomly selected within the `TEMP_RANGES` for its spectral class,
            and the subclass is then derived from this temperature.
        5.  **Mass and Radius Calculation**: Similar to the specified star path,
            mass is determined based on Yerkes class constraints and luminosity,
            and radius is calculated using the appropriate physical laws.

        This comprehensive approach ensures that all generated stars, whether
        user-specified or randomly created, adhere to the fundamental physical
        relationships between their core properties, resulting in astrophysically
        plausible stellar objects.
        """
        yerkes_lookup = YERKES_CLASS_NAMES
        if initial_mass_sol is not None or (not self.system_config.STAR_TYPE and mass_override is None):
            self._generate_from_population_model(initial_mass_sol, age_gy)
            return

        if self.system_config.STAR_TYPE:
            # --- GENERATE STAR FROM SPECIFIED TYPE ---

            # 1. Parse and validate the specified star type string.
            match = STAR_TYPE_PATTERN.fullmatch(self.system_config.STAR_TYPE.upper())
            if not match:
                raise ValueError("Invalid star type format. Expected format is e.g., G2V.")
            spectral_class, subclass_str, yerkes_class_str = match.groups()
            subclass = int(subclass_str)
            self.yerkes_class = yerkes_class_str
            yerkes_type = yerkes_lookup[yerkes_class_str]

            # 2. Calculate Temperature from spectral class and subclass.
            if yerkes_class_str in ["VII", "D"] and spectral_class in constants.HOT_WHITE_DWARF_TEMP_RANGES:
                min_temp, max_temp = constants.HOT_WHITE_DWARF_TEMP_RANGES[spectral_class]
            else:
                min_temp, max_temp = constants.TEMP_RANGES[spectral_class]
            temp_range_size = max_temp - min_temp
            temperature = min_temp + (constants.SUBCLASS_MAX_VALUE - subclass) * (temp_range_size / constants.SUBCLASS_MAX_VALUE)
            temperature = int(round(temperature, tuning.ROUND_TEMPERATURE_NEAREST_HUNDRED))

            # 3. Determine a physically valid Luminosity.
            # Find the overlapping luminosity range between the spectral and Yerkes classes.
            spec_min_lum, spec_max_lum = constants.SPECTRAL_LUMINOSITY_RANGES[spectral_class]
            yerkes_min_lum, yerkes_max_lum = constants.YERKES_LUMINOSITY_RANGES[yerkes_class_str]
            
            # Special case for hot, young white dwarfs, which can be temporarily very luminous.
            if yerkes_class_str in ["VII", "D"] and spectral_class in ["O", "B"]:
                yerkes_min_lum, yerkes_max_lum = constants.HOT_WHITE_DWARF_LUMINOSITY_RANGE_SOL

            valid_min_lum = max(spec_min_lum, yerkes_min_lum)
            valid_max_lum = min(spec_max_lum, yerkes_max_lum)
            
            if valid_min_lum > valid_max_lum:
                # If there's no overlap, the combination is physically unlikely.
                # We will prioritize the Yerkes class range, as it's the primary
                # driver of luminosity for evolved stars.
                valid_min_lum, valid_max_lum = yerkes_min_lum, yerkes_max_lum

            # Log-uniform: a range spanning decades drawn linearly lands near
            # its top almost every time.
            luminosity = math.exp(draw.uniform(math.log(valid_min_lum), math.log(valid_max_lum)))

        else:
            # --- GENERATE STAR RANDOMLY ---

            # 1. Generate Spectral Class based on galactic population.
            if self.system_config.LARGE_STAR:
                spectral_probabilities = tuning.SPECTRAL_PROBABILITIES_LARGE_STAR
                table_name = "SPECTRAL_PROBABILITIES_LARGE_STAR"
            else:
                spectral_probabilities = tuning.SPECTRAL_PROBABILITIES_NORMAL
                table_name = "SPECTRAL_PROBABILITIES_NORMAL"
            spectral_class = draw.choices(list(spectral_probabilities.keys()), weights=spectral_probabilities.values(), k=1)[0]
            log.choice("Spectral class", spectral_class,
                       f"weighted draw from {table_name} (system_config.LARGE_STAR="
                       f"{self.system_config.LARGE_STAR})")

            # 2. Generate Luminosity from the spectral class's typical range.
            min_luminosity, max_luminosity = constants.SPECTRAL_LUMINOSITY_RANGES[spectral_class]
            luminosity = draw.uniform(min_luminosity, max_luminosity)

            # 3. Determine Yerkes Class from the resulting luminosity.
            if luminosity > constants.YERKES_LUMINOSITY_RANGES["0"][0]:
                self.yerkes_class, yerkes_type = "0", "Hypergiant"
            elif luminosity > constants.YERKES_LUMINOSITY_RANGES["IA"][0]:
                self.yerkes_class, yerkes_type = "IA", "Supergiant"
            elif luminosity > constants.YERKES_LUMINOSITY_RANGES["IAB"][0]:
                self.yerkes_class, yerkes_type = "IAB", "Intermediate-size Luminous Supergiant"
            elif luminosity > constants.YERKES_LUMINOSITY_RANGES["IB"][0]:
                self.yerkes_class, yerkes_type = "IB", "Less Luminous Supergiant"
            elif luminosity > constants.YERKES_LUMINOSITY_RANGES["II"][0]:
                self.yerkes_class, yerkes_type = "II", "Bright Giant"
            elif luminosity > constants.YERKES_LUMINOSITY_RANGES["III"][0]:
                self.yerkes_class, yerkes_type = "III", "Giant"
            elif luminosity > constants.YERKES_LUMINOSITY_RANGES["IV"][0]:
                self.yerkes_class, yerkes_type = "IV", "Subgiant"
            elif luminosity > constants.SPECTRAL_LUMINOSITY_RANGES["M"][0]: # Check against dimmest main sequence
                self.yerkes_class, yerkes_type = "V", "Main Sequence"
            else:
                self.yerkes_class, yerkes_type = "VII", "White Dwarf"

            log.choice("Yerkes luminosity class", self.yerkes_class,
                       f"luminosity {luminosity:.4g} Lsun falls into the {yerkes_type} threshold band")

            # 4. Calculate Temperature and Subclass.
            min_temp, max_temp = constants.TEMP_RANGES[spectral_class]
            temperature = int(round(draw.uniform(min_temp, max_temp), tuning.ROUND_TEMPERATURE_NEAREST_HUNDRED))
            temp_range_size = max_temp - min_temp
            subclass = constants.SUBCLASS_MAX_VALUE - round((temperature - min_temp) / temp_range_size * constants.SUBCLASS_MAX_VALUE)

        # --- CALCULATE FINAL PROPERTIES (COMMON TO BOTH PATHS) ---

        # 5. Calculate Mass based on Yerkes class constraints.
        min_mass, max_mass = constants.YERKES_MASS_CONSTRAINTS[self.yerkes_class]
        
        if self.yerkes_class == "V":
            # For main-sequence stars, the mass-luminosity relation is strong.
            if mass_override:
                mass_sol = mass_override / constants.SOLAR_MASS_TO_KG
            else:
                mass_sol = luminosity ** (1 / constants.MAIN_SEQUENCE_MASS_LUMINOSITY_EXPONENT)
        elif self.yerkes_class in ["VII", "D"]:
            # For white dwarfs, mass is tightly constrained. Hotter (younger) ones
            # are typically more massive, closer to the Chandrasekhar limit.
            if spectral_class in ["O", "B"]:
                mass_sol = _sample_hot_white_dwarf_mass_sol()
            else:
                mass_sol = draw.uniform(min_mass, constants.COOL_WHITE_DWARF_MAX_MASS_SOL)
            if mass_override: # If mass is overridden for a WD, ensure it's within limits
                mass_sol = max(min(mass_override / constants.SOLAR_MASS_TO_KG, constants.CHANDRASEKHAR_LIMIT_SOL), min_mass)
        else:
            # For giants and supergiants, mass is less predictable from luminosity alone.
            # We choose a random mass within the physically allowed range for the class,
            # rejecting and resampling any draw whose implied main-sequence lifespan would
            # already exceed the age of the universe (see _sample_evolved_star_mass_sol) --
            # otherwise a sub-solar-mass progenitor could be assigned to a class that
            # requires it to have already finished a main-sequence phase that hasn't had
            # time to happen yet. Yerkes class VI (subdwarf) is deliberately excluded from
            # this check -- its age/lifespan comes from an entirely separate, mass-independent
            # path (see _calculate_initial_star_age_and_lifespan's Yerkes-VI branch), so this
            # check's own rationale doesn't apply to it, and its whole allowed mass range
            # would otherwise be rejected outright (see _sample_evolved_star_mass_sol's
            # docstring).
            if mass_override:
                mass_sol = mass_override / constants.SOLAR_MASS_TO_KG
            elif self.yerkes_class == "VI":
                mass_sol = draw.uniform(min_mass, max_mass)
            else:
                mass_sol = _sample_evolved_star_mass_sol(min_mass, max_mass)


        # Ensure the calculated mass is within the absolute physical bounds for its class.
        mass_sol = max(min(mass_sol, max_mass), min_mass)
        mass = mass_sol * constants.SOLAR_MASS_TO_KG

        # 6. Calculate Radius based on the star's type.
        if self.yerkes_class in ["VII", "D"]:
            # White dwarf radius follows an inverse mass-radius relationship.
            # R ∝ M^(-1/3). A 1 solar mass WD is the base.
            radius = constants.WHITE_DWARF_BASE_RADIUS_KM * (mass_sol ** constants.WHITE_DWARF_MASS_RADIUS_EXPONENT)
        else:
            # For all other stars, radius is calculated from luminosity and temperature
            # using the Stefan-Boltzmann law.
            luminosity_watts = luminosity * constants.SOLAR_LUMINOSITY
            radius = math.sqrt(luminosity_watts / (constants.FOUR_PI * constants.STEFAN_BOLTZMANN_CONSTANT * temperature ** 4)) / constants.KM_TO_M_FACTOR

        # 7. Set final star properties.
        color_descriptions = constants.SPECTRAL_CLASS_COLORS
        star_type_str = f"{spectral_class}{subclass}{self.yerkes_class} {color_descriptions[spectral_class]} {yerkes_type} Star"

        self.type = star_type_str
        self.radius = radius
        self.mass = mass
        self.temperature = temperature
        self.luminosity = luminosity * constants.SOLAR_LUMINOSITY


def adjust_pair_age_for_planets(primary, secondary, primary_planets, secondary_planets):
    """
    Settles one shared age for a binary pair's two stars (GEN.53): old
    enough for every planet each star hosts (judged by that star's own
    evolutionary scales), and no older than either star's generated state
    allows. The primary's `adjust_age_for_planets` does the work, bounded
    by the companion's `age_ceiling_gy`; the companion then takes the
    result. Both stars start at the same age (the companion is born with
    the primary), so neither moves outside what it was generated as.

    Args:
        primary (Star): The heavier star.
        secondary (Star): Its companion.
        primary_planets (list): Bodies judged against the primary's scales.
        secondary_planets (list): Bodies judged against the companion's (a
            close pair passes its circumbinary planets for both).
    """
    primary.adjust_age_for_planets(primary_planets,
                                   min_required_age_gy=secondary.planet_age_requirement_gy(secondary_planets),
                                   age_ceiling_gy=secondary.age_ceiling_gy())
    secondary.age = primary.age


