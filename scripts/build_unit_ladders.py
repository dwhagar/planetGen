#!/usr/bin/env python3
"""
Writes the unit ladders (planetgen/util/ladders.py) to the browser's copy,
src/html/static/unitladders.js, which html/static/unitladder.js reads (UX.23).

    python scripts/build_unit_ladders.py          write the file
    python scripts/build_unit_ladders.py --check  exit 1 when the file is out of date

tests/test_unit_ladders.py runs the check, so a change to a ladder fails the
suite until this script has been run.
"""

import dataclasses
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from planetgen.util import ladders  # noqa: E402

OUTPUT = os.path.join(ROOT, "src", "html", "static", "unitladders.js")


def _rung(rung):
    """A rung as the browser reads it: `start` always resolved to a number."""
    data = dataclasses.asdict(rung)
    data["start"] = rung.factor if rung.start is None else rung.start
    return data


def _json(value):
    """`value` as a JavaScript literal on one line."""
    return json.dumps(value, ensure_ascii=False)


def render():
    """The text of `unitladders.js`."""
    blocks = []
    for ladder in ladders.LADDERS:
        rungs = ",\n".join("      " + _json(_rung(rung)) for rung in ladder.rungs)
        blocks.append(
            f"  {_json(ladder.quantity)}: {{\n"
            f"    \"base\": {_json(ladder.base)}, \"nonfinite\": {_json(ladder.nonfinite)}, \"zero\": {_json(ladder.zero)},\n"
            f"    \"asides\": {_json([list(aside) for aside in ladder.asides])},\n"
            f"    \"rungs\": [\n{rungs},\n    ],\n"
            f"  }},\n")
    return (
        "// html/static/unitladders.js\n"
        "//\n"
        "// GENERATED by scripts/build_unit_ladders.py from planetgen/util/ladders.py:\n"
        "// do not edit by hand. The unit ladders (UX.23) that unitladder.js reads.\n"
        "\n"
        "export const LADDERS = {\n" + "".join(blocks) + "};\n"
    )


def main(argv):
    text = render()
    if "--check" in argv:
        with open(OUTPUT, encoding="utf-8") as handle:
            if handle.read() != text:
                print(f"{os.path.relpath(OUTPUT, ROOT)} is out of date: run scripts/build_unit_ladders.py")
                return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
