#!/usr/bin/env python3
"""
The region-query benchmark (TEST.165; docs/design/galaxy/spherical-region-queries.md sections 8 and 9 item 6): the recommended cell-key statement
(`planetgen.db.region`) against the plain box over an index on the three coordinates and the sector walk NAV.43 used before the key, on the real
`star_systems` table of a database, warm and cold.

    python3 scripts/bench_region_queries.py grow  --target 3000000 --seed 1     # fill a ball around the Sun from the rows the database holds
    python3 scripts/bench_region_queries.py run   --label warm --centres 16     # time the three designs at 1, 5, 10, 25 and 50 pc
    python3 scripts/bench_region_queries.py run   --label cold --centres 8      # after a restart with a small buffer pool and O_DIRECT

The connection is `--mysql-*` or `PLANETGEN_MYSQL_*`, as for every command. `grow` and `run` change only the database they are given, so give them a
scratch one (`planetgen_bench`), never a galaxy anyone uses.

What `grow` does. A galaxy of millions of systems takes days to generate (the generator makes about a system every few seconds on one core), so the
database holds a few hundred systems generated by the real generator (`planetgen sector` or `generate_and_save_sector_at`) and `grow` copies them:
each new row is a copy of one real row, wide as a real row is, with its position moved to a point drawn uniformly in a ball around the Sun at the Sun's
density (0.12 systems per cubic parsec, the research's S sets), the real sector of that point (`sector_address_at`, a `sectors` row made for each
occupied cell with the real centre) and its sector-local position. The copies keep the real rows' other values; their `uid` is NULL. The cost of a
region query follows the rows read and the page layout, not what a row says, so the copies stand for a generated galaxy; the figures are not the
figures of one (the copies repeat a few hundred rows, so a row's neighbours in the table are not its neighbours in space, as in a galaxy built from
several runs).

What `run` does. The centres are the database's own systems inside 0.7 of the ball's radius. For each radius and design it times each centre once
(planning, statement and fetch, in Python), checks that the three designs return the same set of systems, and reports the median and the rows
returned. The box needs an index on the three coordinates, which `run` adds as `idx_bench_box` if it is missing (the schema has none). Results go to
`--out` as JSON and to the screen as a table.
"""

import argparse
import json
import math
import os
import random
import statistics
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from planetgen import tuning                                                   # noqa: E402
from planetgen.db import region, store                                         # noqa: E402
from planetgen.galaxy import frame, spherical                                  # noqa: E402
from planetgen.physics.units import ly_to_pc                                   # noqa: E402

SUN_PC = (8122.0, 0.0, 20.8)
"""tuple: The centre of the grown ball, parsecs in the galaxy frame (the Sun's distance from the centre and its height above the plane)."""

DENSITY_PER_PC3 = 0.12
"""float: Systems per cubic parsec in the grown ball: the research's S sets (the Sun's neighbourhood)."""

COUNT_NAME = "key count"
RADII_PC = (1.0, 5.0, 10.0, 25.0, 50.0)
POSITION = ("p.galaxy_x_pc", "p.galaxy_y_pc", "p.galaxy_z_pc")
BATCH = 20_000
SECTOR_CHUNK = 400


def _connect(args):
    config = store.mysql_config_from_args(args)
    return store.get_connection(config), config


def _columns_to_copy(conn):
    """The columns of `star_systems` a copy carries over as they are: everything the grown row does not set itself."""
    skip = {"id", "uid", "sector_id", "cell_key", "position_x_mpc", "position_y_mpc", "position_z_mpc",
            "galaxy_x_pc", "galaxy_y_pc", "galaxy_z_pc", "created_at", "modified_at"}
    rows = conn.execute("SELECT column_name AS c FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = 'star_systems' "
                        "AND generation_expression = '' ORDER BY ordinal_position").fetchall()
    return [row["c"] for row in rows if row["c"] not in skip]


def grow(args):
    conn, _config = _connect(args)
    rng = random.Random(args.seed)
    edge_pc = ly_to_pc(tuning.DEFAULT_SECTOR_EDGE_LY)
    templates = [row["id"] for row in conn.execute("SELECT id FROM star_systems WHERE galaxy_x_pc IS NOT NULL ORDER BY id").fetchall()]
    if not templates:
        sys.exit("the database holds no real star system to copy: generate a few sectors first")
    have = conn.execute("SELECT COUNT(*) AS n FROM star_systems").fetchone()["n"]
    want = args.target - have
    if want <= 0:
        print(f"{have} systems already")
        return
    radius = (args.target / (4.0 / 3.0 * math.pi * DENSITY_PER_PC3)) ** (1.0 / 3.0)
    print(f"growing {have} -> {args.target} systems in a ball of {radius:.1f} pc around {SUN_PC}", flush=True)
    columns = _columns_to_copy(conn)
    conn.execute("DROP TABLE IF EXISTS bench_clone")
    conn.execute("CREATE TABLE bench_clone (n BIGINT UNSIGNED PRIMARY KEY, template_id BIGINT UNSIGNED NOT NULL, sector_id BIGINT UNSIGNED NOT NULL, "
                 "px DOUBLE NOT NULL, py DOUBLE NOT NULL, pz DOUBLE NOT NULL, gx DOUBLE NOT NULL, gy DOUBLE NOT NULL, gz DOUBLE NOT NULL) ENGINE=InnoDB")
    sector_ids = {}
    started = time.time()
    made = 0
    while made < want:
        batch = []
        while len(batch) < min(BATCH, want - made):
            x, y, z = (rng.uniform(-radius, radius) for _ in range(3))
            if x * x + y * y + z * z > radius * radius:
                continue
            point = (SUN_PC[0] + x, SUN_PC[1] + y, SUN_PC[2] + z)
            address = spherical.sector_address_at(point, edge_pc)
            if address not in sector_ids:
                centre = spherical.sector_position_pc(*address, edge_pc)
                found = conn.execute("SELECT id FROM sectors WHERE shell_index = ? AND band_index = ? AND wedge_index = ?", address).fetchone()
                if found is None:
                    conn.execute("INSERT INTO sectors (name, edge_mpc, center_x_pc, center_y_pc, center_z_pc, galactic_radius_pc, shell_index, band_index, wedge_index) "
                                 "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                                 (f"Bench {address[0]}-{address[1]}-{address[2]}", edge_pc * 1000.0, *centre, math.hypot(*centre), *address))
                    found = conn.execute("SELECT id FROM sectors WHERE shell_index = ? AND band_index = ? AND wedge_index = ?", address).fetchone()
                sector_ids[address] = (found["id"], centre)
            sector_id, centre = sector_ids[address]
            local = frame.galaxy_to_local_pc(centre, point)
            batch.append((have + made + len(batch) + 1, rng.choice(templates), sector_id, *(value * 1000.0 for value in local), *point))
        conn.executemany("INSERT INTO bench_clone VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", batch)
        made += len(batch)
        print(f"  planned {made}/{want} ({time.time() - started:.0f} s, {len(sector_ids)} sectors)", flush=True)
    names = ", ".join(columns)
    select = ", ".join(f"t.{c}" for c in columns)
    total = conn.execute("SELECT COUNT(*) AS n FROM bench_clone").fetchone()["n"]
    for low in range(1, total + 1, 100_000):
        conn.execute(f"INSERT INTO star_systems ({names}, sector_id, position_x_mpc, position_y_mpc, position_z_mpc, galaxy_x_pc, galaxy_y_pc, galaxy_z_pc) "
                     f"SELECT {select}, c.sector_id, c.px, c.py, c.pz, c.gx, c.gy, c.gz FROM bench_clone c JOIN star_systems t ON t.id = c.template_id "
                     f"WHERE c.n BETWEEN {have + low} AND {have + low + 99_999}")
        print(f"  inserted {min(low + 99_999, total)}/{total} ({time.time() - started:.0f} s)", flush=True)
    conn.execute("DROP TABLE bench_clone")
    conn.execute("ANALYZE TABLE star_systems")
    print(f"done in {time.time() - started:.0f} s: {conn.execute('SELECT COUNT(*) AS n FROM star_systems').fetchone()['n']} systems, "
          f"{conn.execute('SELECT COUNT(*) AS n FROM sectors').fetchone()['n']} sectors", flush=True)


# --- the three designs ------------------------------------------------------------------------------------------------------------------------


def by_key(conn, center, radius):
    rows = region.region_rows(conn, "star_systems", "p.id", POSITION, center, radius)
    return {row["id"] for row in rows if row["d2"] <= radius * radius * (1 + 1e-9)}


def by_box(conn, center, radius):
    cx, cy, cz = center
    rows = conn.execute(
        "SELECT id, (galaxy_x_pc - ?) * (galaxy_x_pc - ?) + (galaxy_y_pc - ?) * (galaxy_y_pc - ?) + (galaxy_z_pc - ?) * (galaxy_z_pc - ?) AS d2 "
        "FROM star_systems FORCE INDEX (idx_bench_box) WHERE galaxy_x_pc BETWEEN ? AND ? AND galaxy_y_pc BETWEEN ? AND ? AND galaxy_z_pc BETWEEN ? AND ? "
        "HAVING d2 <= ?",
        (cx, cx, cy, cy, cz, cz, cx - radius, cx + radius, cy - radius, cy + radius, cz - radius, cz + radius, radius * radius * (1 + 1e-9))).fetchall()
    return {row["id"] for row in rows}


def by_sector_walk(conn, center, radius):
    """The path of `src/planetgen/db/near.py` before the key: the sectors whose centre lies in the box, their systems, the exact distance in Python."""
    reach = radius + 1.5 * EDGE_PC
    cx, cy, cz = center
    sectors = conn.execute("SELECT id, center_x_pc, center_y_pc, center_z_pc FROM sectors WHERE center_x_pc BETWEEN ? AND ? AND center_y_pc BETWEEN ? AND ? "
                           "AND center_z_pc BETWEEN ? AND ?", (cx - reach, cx + reach, cy - reach, cy + reach, cz - reach, cz + reach)).fetchall()
    centres = {row["id"]: (row["center_x_pc"], row["center_y_pc"], row["center_z_pc"]) for row in sectors}
    found = set()
    ids = list(centres)
    for start in range(0, len(ids), SECTOR_CHUNK):
        chunk = ids[start:start + SECTOR_CHUNK]
        rows = conn.execute(f"SELECT id, sector_id, position_x_mpc, position_y_mpc, position_z_mpc FROM star_systems WHERE sector_id IN ({', '.join('?' for _ in chunk)})",
                            tuple(chunk)).fetchall()
        for row in rows:
            point = frame.local_to_galaxy_pc(centres[row["sector_id"]], (row["position_x_mpc"] / 1000.0, row["position_y_mpc"] / 1000.0, row["position_z_mpc"] / 1000.0))
            if (point[0] - cx) ** 2 + (point[1] - cy) ** 2 + (point[2] - cz) ** 2 <= radius * radius * (1 + 1e-9):
                found.add(row["id"])
    return found


EDGE_PC = ly_to_pc(tuning.DEFAULT_SECTOR_EDGE_LY)
DESIGNS = (("key", by_key), ("box", by_box), ("sector walk", by_sector_walk))


def run(args):
    conn, _config = _connect(args)
    if not conn.execute("SHOW INDEX FROM star_systems WHERE Key_name = 'idx_bench_box'").fetchall():
        conn.execute("ALTER TABLE star_systems ADD INDEX idx_bench_box (galaxy_x_pc, galaxy_y_pc, galaxy_z_pc)")
    total = conn.execute("SELECT COUNT(*) AS n FROM star_systems").fetchone()["n"]
    radius = (total / (4.0 / 3.0 * math.pi * DENSITY_PER_PC3)) ** (1.0 / 3.0)
    rng = random.Random(args.seed)
    centres = []
    while len(centres) < args.centres:
        row = conn.execute("SELECT galaxy_x_pc, galaxy_y_pc, galaxy_z_pc FROM star_systems WHERE id = ?",
                           (rng.randint(1, conn.execute("SELECT MAX(id) AS m FROM star_systems").fetchone()["m"]),)).fetchone()
        if row is None:
            continue
        point = (row["galaxy_x_pc"], row["galaxy_y_pc"], row["galaxy_z_pc"])
        if math.dist(point, SUN_PC) <= 0.7 * radius:
            centres.append(point)
    pool = conn.execute("SHOW VARIABLES WHERE Variable_name IN ('innodb_buffer_pool_size', 'innodb_flush_method', 'version')").fetchall()
    settings = {row["Variable_name"]: row["Value"] for row in pool}
    results = {"label": args.label, "systems": total, "ball_radius_pc": radius, "centres": len(centres), "mysql": settings, "cells": {}}
    print(f"{args.label}: {total} systems, {len(centres)} centres, {settings}", flush=True)
    for _ in range(args.warmup):    # the same queries, not reported: the pages they read are in the buffer pool afterwards
        for radius_pc in RADII_PC:
            for centre in centres:
                for _name, design in DESIGNS:
                    design(conn, centre, radius_pc)
    print(f"{'radius':>7} {'design':<12} {'median ms':>10} {'max ms':>9} {'median rows':>12}", flush=True)
    for radius_pc in RADII_PC:
        times = {name: [] for name, _design in DESIGNS}
        counts = {name: [] for name, _design in DESIGNS}
        times[COUNT_NAME], counts[COUNT_NAME] = [], []
        for centre in centres:
            began = time.perf_counter()     # the same statement as by_key, counted in SQL: the figure the design note's 42 ms is (no rows returned)
            counted = region.capped_count(conn, "star_systems", POSITION, centre, radius_pc, 10**9)
            times[COUNT_NAME].append((time.perf_counter() - began) * 1000.0)
            counts[COUNT_NAME].append(counted)
            expected = None
            for name, design in DESIGNS:
                began = time.perf_counter()
                found = design(conn, centre, radius_pc)
                times[name].append((time.perf_counter() - began) * 1000.0)
                counts[name].append(len(found))
                if expected is None:
                    expected = found
                elif found != expected:
                    sys.exit(f"{name} and key disagree at {centre}, {radius_pc} pc: {len(found)} against {len(expected)}")
        for name in [COUNT_NAME] + [name for name, _design in DESIGNS]:
            results["cells"][f"{radius_pc:g}|{name}"] = {"median_ms": statistics.median(times[name]), "max_ms": max(times[name]),
                                                         "median_rows": statistics.median(counts[name])}
            print(f"{radius_pc:>6g}  {name:<12} {statistics.median(times[name]):>10.1f} {max(times[name]):>9.1f} {statistics.median(counts[name]):>12.0f}", flush=True)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            json.dump(results, handle, indent=1)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1] if __doc__ else "")
    store.add_mysql_connection_args(parser)
    sub = parser.add_subparsers(dest="command", required=True)
    grow_parser = sub.add_parser("grow", help="fill a ball around the Sun with copies of the real rows")
    grow_parser.add_argument("--target", type=int, default=3_000_000)
    grow_parser.add_argument("--seed", type=int, default=1)
    run_parser = sub.add_parser("run", help="time the three designs")
    run_parser.add_argument("--label", default="warm")
    run_parser.add_argument("--centres", type=int, default=16)
    run_parser.add_argument("--seed", type=int, default=1)
    run_parser.add_argument("--warmup", type=int, default=0, help="passes over every query before timing (warm run 1, cold run 0)")
    run_parser.add_argument("--out", default="")
    args = parser.parse_args(argv)
    {"grow": grow, "run": run}[args.command](args)


if __name__ == "__main__":
    main()
