#!/usr/bin/env python3
"""
Builds the code-derived reference pages that cannot drift from the code: `docs/generated/database-columns.md` (every
table and column of `src/planetgen/db/schema.sql`, with the type and the column's own comment) and
`docs/generated/api-routes.md` (every HTTP route under `src/planetgen/api/`, with its methods and the first sentence of
its docstring).

Boss (2026-11-08, 6:13 PM EST): "a full refresh of ALL documents of ALL types". The hand-written references
(`docs/reference/database-schema.md`, `api.md`) say what things mean; these two lists say what exists, so a table, column
or route added without a hand-written line is still found. They are global documents (DOC.69): the TODO thread rebuilds
them with `scripts/build_global_docs.py`.

Usage
=====
    python scripts/build_reference_inventory.py            # write both pages
    python scripts/build_reference_inventory.py --check    # fail if either is out of date
"""

import argparse
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMA = os.path.join(ROOT, "src", "planetgen", "db", "schema.sql")
API = os.path.join(ROOT, "src", "planetgen", "api")
OUT = os.path.join(ROOT, "docs", "generated")

_TABLE = re.compile(r"^CREATE TABLE IF NOT EXISTS (\w+) \($", re.M)
_COLUMN = re.compile(r"^\s{4}(\w+)\s+([A-Z]+(?:\([^)]*\))?(?:\s+UNSIGNED)?)(.*)$")
_KEYWORDS = {"CONSTRAINT", "UNIQUE", "PRIMARY", "KEY", "INDEX", "FOREIGN", "CHECK"}


def _cell(text):
    return text.replace("|", "\\|").strip()


def database_columns():
    """The text of `database-columns.md`."""
    with open(SCHEMA, encoding="utf-8") as handle:
        sql = handle.read()
    out = ["# Database columns", "",
           "Generated by `scripts/build_reference_inventory.py` from [schema.sql](../../src/planetgen/db/schema.sql); "
           "do not edit by hand. What each table means is in [database-schema.md](../reference/database-schema.md); "
           "this list is every table and column the schema creates, with the comment written beside it.", ""]
    matches = list(_TABLE.finditer(sql))
    out.append(f"{len(matches)} tables.")
    out.append("")
    for i, match in enumerate(matches):
        name = match.group(1)
        end = sql.index("\n) ENGINE", match.end())
        body = sql[match.end():end]
        before = sql[:match.start()].rstrip().split("\n")
        notes = []
        for line in reversed(before):
            if not line.startswith("--"):
                break
            notes.append(line.lstrip("-").strip())
        notes = [n for n in reversed(notes) if n and set(n) != {"-"}]
        out.append(f"## `{name}`")
        out.append("")
        if notes:
            out.append(_cell(" ".join(notes))[:1200])
            out.append("")
        rows = []
        for line in body.split("\n"):
            column = _COLUMN.match(line)
            if not column or column.group(1).upper() in _KEYWORDS:
                continue
            rest = column.group(3)
            comment = rest.split("--", 1)[1].strip() if "--" in rest else ""
            flags = "NOT NULL" if ("NOT NULL" in rest.upper() or "PRIMARY KEY" in rest.upper()) else "NULL"
            rows.append(f"| `{column.group(1)}` | {column.group(2)} | {flags} | {_cell(comment)} |")
        out.append("| Column | Type | Null | Meaning |")
        out.append("|---|---|---|---|")
        out += rows
        out.append("")
    return "\n".join(out)


def _routes_of(path):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()
    prefix = re.search(r'Blueprint\([^)]*url_prefix="([^"]*)"', source)
    prefix = prefix.group(1) if prefix else ""
    found = []
    for node in ast.walk(ast.parse(source)):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            if not (isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Attribute) and decorator.func.attr == "route"
                    and decorator.args and isinstance(decorator.args[0], ast.Constant)):
                continue
            methods = "GET"
            for keyword in decorator.keywords:
                if keyword.arg == "methods":
                    methods = ", ".join(c.value for c in keyword.value.elts if isinstance(c, ast.Constant))
            doc = " ".join((ast.get_docstring(node) or "").split())
            sentence = re.match(r"(.+?[.!?])(\s|$)", doc)
            text = sentence.group(1) if sentence else doc
            found.append((prefix + decorator.args[0].value, methods, text[:300], node.name))
    return found


def api_routes():
    """The text of `api-routes.md`."""
    rows = []
    for name in sorted(os.listdir(API)):
        if name.endswith(".py"):
            for route, methods, text, function in _routes_of(os.path.join(API, name)):
                rows.append((route, methods, name, function, text))
    rows.sort()
    out = ["# API routes", "",
           "Generated by `scripts/build_reference_inventory.py` from the route decorators under "
           "[src/planetgen/api/](../../src/planetgen/api/); do not edit by hand. What each route takes and returns is in "
           "[api.md](../reference/api.md); this list is every route the code registers.", "",
           f"{len(rows)} routes.", "", "| Route | Methods | Defined in | What it does |", "|---|---|---|---|"]
    for route, methods, name, function, text in rows:
        out.append(f"| `{route}` | {methods} | `{name}` `{function}` | {_cell(text)} |")
    out.append("")
    return "\n".join(out)


PAGES = {"database-columns.md": database_columns, "api-routes.md": api_routes}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a page is out of date")
    args = parser.parse_args(argv)
    stale = []
    for name, build in PAGES.items():
        text = build()
        path = os.path.join(OUT, name)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            stale.append(name)
            if not args.check:
                with open(path, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(text)
    if args.check:
        if stale:
            print(f"out of date: {', '.join(stale)}; run python scripts/build_reference_inventory.py")
            return 1
        print("reference inventory is up to date")
        return 0
    print(f"wrote {len(PAGES)} pages ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
