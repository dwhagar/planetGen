#!/usr/bin/env python3
"""
Writes the unit registry (planetgen/physics/unit_registry.py) to the browser's copy,
src/html/static/unitregistry.js (UX.140), the table `unitladder.js` and every script that holds a value next to its unit
read their factors from.

    python scripts/build_unit_registry.py          write the file
    python scripts/build_unit_registry.py --check  exit 1 when the file is out of date

tests/test_unit_registry_js.py runs the check, so a change to the registry fails the suite until this script has been run.
"""

import dataclasses
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from planetgen.physics import unit_registry  # noqa: E402

OUTPUT = os.path.join(ROOT, "src", "html", "static", "unitregistry.js")

FUNCTIONS = '''
const TEN_POWERS = Array.from({ length: 23 }, (_unused, exponent) => Number(`1e${exponent}`));

export function unit(key) {
  const row = UNITS[key];
  if (row === undefined) throw new Error(`unknown unit ${key}`);
  return row;
}

// `value` of the unit `key` in its kind's base unit (physics/unit_registry.py `to_base`).
export function toBase(value, key) {
  const row = unit(key);
  return row.offset ? value * row.factor + row.offset : value * row.factor;
}

// A base value in the unit `key` (`from_base`).
export function fromBase(baseValue, key) {
  const row = unit(key);
  return row.offset ? (baseValue - row.offset) / row.factor : baseValue / row.factor;
}

// `value * sourceFactor / targetFactor`, one correctly rounded step where the ratio is a power of ten (`scale`).
export function scale(value, sourceFactor, targetFactor) {
  const ratio = sourceFactor / targetFactor;
  if (ratio > 0 && Number.isFinite(ratio)) {
    const exponent = Math.round(Math.log10(ratio));
    if (exponent >= -22 && exponent <= 22 && Math.abs(ratio - Number(`1e${exponent}`)) <= 1e-14 * ratio) {
      return exponent >= 0 ? value * TEN_POWERS[exponent] : value / TEN_POWERS[-exponent];
    }
  }
  return (value * sourceFactor) / targetFactor;
}

// `value` of the unit `from` in the unit `to`, both of one kind (`convert`).
export function convert(value, from, to) {
  const source = unit(from);
  const target = unit(to);
  if (source.kind !== target.kind) throw new Error(`cannot convert ${source.symbol} (${source.kind}) to ${target.symbol} (${target.kind})`);
  if (source.factor === target.factor && source.offset === target.offset) return value;
  if (source.offset === target.offset) return scale(value, source.factor, target.factor);
  return (value * source.factor + source.offset - target.offset) / target.factor;
}
'''


def _json(value):
    """`value` as a JavaScript literal on one line."""
    return json.dumps(value, ensure_ascii=False)


def _unit(row):
    return {"kind": row.kind, "symbol": row.symbol, "name": row.name, "singular": row.singular or row.name,
            "factor": row.factor, "offset": row.offset}


def _kind(row):
    return {"base": row.base, "dimension": list(row.dimension), "low": row.bounds.low, "high": row.bounds.high,
            "lowOpen": row.bounds.low_open, "highOpen": row.bounds.high_open}


def render():
    """The text of `unitregistry.js`."""
    kinds = "".join(f"  {_json(name)}: {_json(_kind(row))},\n" for name, row in unit_registry.KINDS.items())
    units = "".join(f"  {_json(key)}: {_json(_unit(row))},\n" for key, row in unit_registry.UNITS.items())
    return (
        "// html/static/unitregistry.js\n"
        "//\n"
        "// GENERATED by scripts/build_unit_registry.py from planetgen/physics/unit_registry.py:\n"
        "// do not edit by hand. Every unit the site measures in (UX.140): its kind, symbol, name and the\n"
        "// factor and offset to its kind's base unit, and the conversions over them, the same arithmetic as the\n"
        "// Python registry (tests/test_unit_registry_js.py checks every conversion against it).\n"
        "\n"
        "export const KINDS = {\n" + kinds + "};\n"
        "\n"
        "export const UNITS = {\n" + units + "};\n" + FUNCTIONS
    )


def main(argv):
    text = render()
    if "--check" in argv:
        with open(OUTPUT, encoding="utf-8") as handle:
            if handle.read() != text:
                print(f"{os.path.relpath(OUTPUT, ROOT)} is out of date: run scripts/build_unit_registry.py")
                return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
