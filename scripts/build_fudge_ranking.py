#!/usr/bin/env python3
"""
Builds the stand-in ranking by share of the fudge (GEN.1316, part 6 of the fudge table).

    python scripts/build_fudge_ranking.py            # write docs/design/research/stand-in-fudge-ranking.md
    python scripts/build_fudge_ranking.py --check    # build in memory and fail if the committed file differs

The fudge table (`src/planetgen/physics/data/fudge_table.json`, GEN.1313) gives the width of each class quantity and names the five stand-ins that make most of it. This page lists *every* stand-in
that moves a class quantity, with the share of the quantity's variance it makes (the same share the table prints for its top five: `build_fudge_table.column` is the one place that works it out),
and the unreliability score of the ranking report of 11-06 (tier points plus tweak points, 0 best, 12 worst). Read it for what research buys: the stand-in with the largest share of a wide
quantity is the one whose replacement by a measured value shrinks that width the most. If its share of a quantity is `s`, the width of the quantity falls to `sqrt(1 - s)` of itself when that
stand-in is exact, which is the "width falls by" column.

The page is derived from the matrix, the table and the registry only, so two hosts get the same text, and `src/tests/test_fudge_ranking.py` fails when the committed file differs.
"""

import argparse
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))
sys.path.insert(0, HERE)

import build_fudge_table  # noqa: E402
import stand_in_sensitivity  # noqa: E402

OUT = os.path.join(HERE, "..", "docs", "design", "research", "stand-in-fudge-ranking.md")

TWEAK_POINTS = {"L0": 0.0, "L1": 0.5, "L2": 1.0, "L3": 3.0, "L4": 4.0}
"""dict: The points a tweak level adds to the unreliability score (the ranking report of 11-06, section 2: a value hand-tuned or fitted with no source counts much worse than one nudged inside its error bar)."""
MIN_SHARE = 0.01
"""float: A stand-in is listed against a quantity when it makes at least this share of the variance (smaller shares are rounding)."""
CONSTANT_CHARS = 110
"""int: How much of the row's constant cell the page prints."""


def unreliability(tier, tweak):
    """The unreliability score of a row: the tier number minus one plus the tweak points (0 best, 12 worst)."""
    return build_fudge_table.tier_number(tier) - 1 + TWEAK_POINTS.get(tweak or "L4", 4.0)


def shares(matrix, table, rows):
    """
    `{quantity: (sigma, {fill_id: share})}` for every measured quantity of the table: the share of the variance each row makes, worked out by `build_fudge_table.column` with the clip the table
    kept for the quantity (so the shares are the table's, for every row and not only its top five).
    """
    by_id = {row["fill_id"]: row for row in rows}
    found = {}
    for quantity, entry in sorted(table["quantities"].items()):
        if entry["basis"] != "measured":
            continue
        contributions, sigma = build_fudge_table.column(quantity, matrix, by_id, entry["clip"])
        total = sigma * sigma
        found[quantity] = (sigma, {item["fill_id"]: item["variance"] / total for item in contributions} if total else {})
    return found


def shorten(text):
    """A registry cell cut to `CONSTANT_CHARS` on a word, with no table bar in it."""
    text = re.sub(r"\s+", " ", text.replace("|", "/")).strip()
    if len(text) <= CONSTANT_CHARS:
        return text
    return text[:CONSTANT_CHARS].rsplit(" ", 1)[0].rstrip(",;:") + " ..."


def render(matrix, table, rows):
    """The text of the page from the matrix document, the fudge table and the registry `rows` (`stand_in_sensitivity.read_rows`)."""
    by_id = {row["fill_id"]: row for row in rows}
    found = shares(matrix, table, rows)
    per_row = {}
    for quantity, (_, shared) in found.items():
        for fill_id, share in shared.items():
            if share >= MIN_SHARE:
                per_row.setdefault(fill_id, {})[quantity] = share
    out = [
        "# Stand-ins ranked by their share of the fudge (GEN.1316)",
        "",
        "Status: generated by `scripts/build_fudge_ranking.py` from the fudge table (`src/planetgen/physics/data/fudge_table.json`), the sensitivity matrix behind it and the stand-in registry; do not edit it by hand."
        " A test fails when it differs. It is the share-of-fudge column that the stand-in ranking report of 11-06 was to gain (plan section 5, step 6).",
        "",
        "## What the fudge is",
        "",
        "A class edge is a line on a finished quantity (a temperature, a pressure, a gravity, a gas share, the water cover). The quantity is made by a chain of generator steps, and each step uses stand-in values (GEN.725)"
        " whose source we doubt. The fudge width of the quantity is how far it could move if those stand-ins were wrong by what the registry says they could be. It is **the model's uncertainty, not the world's variety**:"
        " a body that sits inside the width of an edge is one the generator cannot yet tell from one on the other side, and the width shrinks by itself when a stand-in is replaced by a measured value and the table is rebuilt.",
        "",
        "## How to read the ranking",
        "",
        "- **Share** is the share of the *variance* of a quantity that one stand-in makes (the movement of the quantity when the stand-in goes across its registered range, widened by the tier factor, clipped at half the gap between two class edges, squared). The shares of a quantity add to 100 percent.",
        "- **Width falls by** is `1 - sqrt(1 - share)`: how much the width of the quantity shrinks if that one stand-in were exact. It is the research payoff, and it is largest for the stand-in with the most share of the widest quantity.",
        "- **Score** is the unreliability score of the ranking report of 11-06: tier number minus one plus the tweak points (L0 0, L1 0.5, L2 1, L3 3, L4 4); 0 best, 12 worst. A stand-in with a high score and a high share is the one to research first; one with a high share and a low score has a source already, and the source's range is the thing to narrow.",
        "- The sample is " + ", ".join(f"{p['systems']} systems of seed {p['seed']}" for p in table["sample"]["passes"]) + f" ({sum(p['bodies'] for p in table['sample']['passes'])} body passes) with the end stages of rocky planets and moons made again.",
        "",
        "## The quantities and what makes their width",
        "",
        "| Quantity | Width | Unit | Basis | Stand-ins that move it | Share from tuned stand-ins (L3, L4) | Largest maker (share) |",
        "|---|---|---|---|---|---|---|",
    ]
    for quantity, entry in sorted(table["quantities"].items()):
        unit = "ln of a ratio" if entry["unit"] == "ln" else "plain"
        if entry["basis"] == "measured":
            top = entry["contributors"][0]
            maker = f"{top['fill_id']} ({top['share'] * 100:.0f}%)"
            tuned = f"{entry['tuned_share'] * 100:.0f}%"
        else:
            maker, tuned = "none (hand shoulder times 1 + score / 12, row FT1)", "-"
        out.append(f"| {quantity} | {entry['width']:.4g} | {unit} | {entry['basis']} | {entry['rows']} | {tuned} | {maker} |")
    out += [
        "",
        "## The stand-ins, largest share of any quantity first",
        "",
        f"Every stand-in that makes at least {MIN_SHARE * 100:.0f} percent of the variance of a class quantity ({len(per_row)} of the {len(rows)} registry rows that have a constant and a knob to move). The shares column names each quantity it moves and its share.",
        "",
        "| Rank | Id | Section | Tier | Tweak | Score | Largest share | Width falls by | Shares of the quantities it moves | What it is |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    ranked = sorted(per_row.items(), key=lambda item: (-max(item[1].values()), item[0]))
    for rank, (fill_id, moved) in enumerate(ranked, start=1):
        row = by_id[fill_id]
        quantity = max(moved, key=lambda name: (moved[name], name))
        share = moved[quantity]
        listed = ", ".join(f"{name} {value * 100:.0f}%" for name, value in sorted(moved.items(), key=lambda item: (-item[1], item[0])))
        out.append(f"| {rank} | {fill_id} | {row['section']} | {row['tier']} | {row['tweak']} | {unreliability(row['tier'], row['tweak']):g} | {quantity} {share * 100:.0f}% | "
                   f"{(1.0 - math.sqrt(1.0 - share)) * 100:.0f}% of {quantity} | {listed} | {shorten(row['constant'])} |")
    return "\n".join(out) + "\n"


def make():
    with open(build_fudge_table.MATRIX, encoding="utf-8") as handle:
        matrix = json.load(handle)
    with open(build_fudge_table.OUT, encoding="utf-8") as handle:
        table = json.load(handle)
    return render(matrix, table, stand_in_sensitivity.read_rows())


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed page differs from the table")
    args = parser.parse_args(argv)
    text = make()
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("docs/design/research/stand-in-fudge-ranking.md is out of date; run python scripts/build_fudge_ranking.py", file=sys.stderr)
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
